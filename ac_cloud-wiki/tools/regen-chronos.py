#!/usr/bin/env python3
"""
regen-chronos — #1789 Cloud Wiki's Chronos pages, baked into the APK from diegonmarcos/lib-chronos at a pinned commit.

  regen-chronos.py                 regenerate from the pin: the assets and the build.json declaration
  regen-chronos.py --check         regenerate into a scratch dir; exit 1 on ANY drift from what is committed (the CI drift check),
                                   and warn when the repo's `ref` has moved past the pin and changed the source dir
  regen-chronos.py --pin <sha|ref> move the pin to a commit (or the tip of a branch), re-hash the vendored files, regenerate
  regen-chronos.py --tree          offline: print the page tree derived from the COMMITTED assets (the guard's view)
  regen-chronos.py --guard         offline: the committed assets, the pin and build.json agree (test/test-chronos.sh)

#1867 the same pin also gives Cloud Wiki its CONTENT and its SIDE MENU: the repo (diegonmarcos/Projects-Library-KG) is one numbered folder
tree whose root wiki.json is generated by the repo's own tools/gen-wiki.py. This tool copies that wiki.json byte for byte to the Cloud
Store runtime dataset (pin `dataset.fleet_path`, the fallback until the app's own clone lands) and writes build.json::ui wiki `pages`
and `groups` from its `menu` (parents = groups, hubs = container pages holding their topics, Chronos = its simulator tree, a project page
carries `project` = its folder); --check and --guard hold both equal.

WHAT IS WRITTEN (APP = ac_cloud-wiki):
  APP/<assets_dir>/<source_dir>/**   every file of lib-chronos <source_dir> at the pin; HTML has each pinned CDN URL replaced by the
                                     path of its vendored copy (absolute, under serve_path), nothing else changed
  APP/<assets_dir>/vendor/**        the CDN files the pages load (tools/chronos-pin.json vendor + fonts), sha256-pinned
  APP/<assets_dir>/GENERATED.md      what this is, the pin, the vendored sources and their licences (DO NOT EDIT)
  APP/build.json                     ui.sections[nav.section].pages[nav.parent].pages = the page tree, one page per index.html in the
                                     repo's own hierarchy: {id, label (the page's <title>), icon, asset (path under assets_dir)};
                                     #1867 and ui.sections[nav.section].pages / groups = the repo's menu (menu_decl)
  APP/<dataset.fleet_path>           #1867 the repo's wiki.json at the pin, byte for byte (the Cloud Store runtime dataset)

The app serves assets_dir at https://appassets.androidplatform.net<serve_path> (WebViewAssetLoader, ui/ChronosPage.kt), so the
pages' relative links keep working and no request leaves the APK. Python 3 stdlib, git and curl; no package manager.
"""
import hashlib, html, json, os, re, shutil, subprocess, sys, tempfile

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIN = os.path.join(APP, "tools", "chronos-pin.json")
BUILD = os.path.join(APP, "build.json")
HEADER = "GENERATED by ac_cloud-wiki/tools/regen-chronos.py from tools/chronos-pin.json. DO NOT EDIT: re-run the tool."
# Tags that make the browser LOAD a URL (an <a href> is a link the user follows; it opens outside the app).
LOADS = re.compile(r"""<(script|link|img|iframe|source|video|audio|embed|object)\b[^>]*?\b(?:src|href|data)\s*=\s*["'](https?:)?//""", re.I)
CSS_URL = re.compile(r"""url\(\s*["']?(https?:)?//""", re.I)
# #1857 a network HINT (<link rel=preconnect|dns-prefetch>) loads nothing but opens a socket to a CDN the APK never uses: the bake drops it
HINT = re.compile(r"""[ \t]*<link\b[^>]*\brel\s*=\s*["']?(?:preconnect|dns-prefetch)["']?[^>]*>[ \t]*\r?\n?""", re.I)


def die(msg):
    print("regen-chronos: " + msg, file=sys.stderr)
    sys.exit(1)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def load_json(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def dump_json(p, d):
    # build.json and the pin are written exactly as they are kept: 2-space indent, ASCII escapes, one trailing newline
    with open(p, "w", encoding="utf-8") as f:
        f.write(json.dumps(d, indent=2, ensure_ascii=True) + "\n")


def fetch(url):
    r = subprocess.run(["curl", "-fsSL", "--retry", "3", "--max-time", "120", "-A", "regen-chronos", url], capture_output=True)
    if r.returncode != 0:
        die("download failed: %s (%s)" % (url, r.stderr.decode(errors="replace").strip()))
    return r.stdout


def git(*a, cwd=None):
    r = subprocess.run(["git", *a], cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        die("git %s failed: %s" % (" ".join(a), r.stderr.strip()))
    return r.stdout.strip()


def checkout(pin, commit, into):
    """A shallow fetch of exactly `commit` (GitHub serves any reachable sha)."""
    git("init", "-q", into)
    git("fetch", "-q", "--depth", "1", pin["url"], commit, cwd=into)
    git("checkout", "-q", "FETCH_HEAD", cwd=into)
    got = git("rev-parse", "HEAD", cwd=into)
    if got != commit:
        die("fetched %s, pinned %s" % (got, commit))


def resolve(pin, ref):
    """A full sha for `ref` (a sha is returned as is when it is 40 hex)."""
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        return ref
    out = git("ls-remote", pin["url"], ref)
    if not out:
        die("%s has no ref %s" % (pin["url"], ref))
    return out.split()[0]


# ── the page tree ────────────────────────────────────────────────────────
def title_of(text, where):
    m = re.search(r"<title[^>]*>(.*?)</title>", text, re.S | re.I)
    if not m:
        die("%s has no <title>: every Chronos page is declared by its own title" % where)
    t = re.sub(r"\s+", " ", html.unescape(m.group(1))).strip()
    if not t:
        die("%s has an empty <title>" % where)
    return t


def natural(s):
    return [int(x) if x.isdigit() else x.lower() for x in re.split(r"(\d+)", s)]


def seg_id(name):
    m = re.match(r"(\d+(?:\.\d+)*)\.", name)
    return m.group(1) if m else re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


CARD = re.compile(r"""<a\b[^>]*\bhref\s*=\s*["']([^"'#?]+)["'][^>]*>(.*?)</a>""", re.S | re.I)
H2 = re.compile(r"<h2[^>]*>(.*?)</h2>", re.S | re.I)


def card_names(root):
    """#1831 the name each page has on the hub page that links to it (a card's <h2>): {rel dir: name}. The repo's own names."""
    names = {}
    for d, dirs, fs in os.walk(root):
        dirs[:] = sorted(x for x in dirs if not x.startswith("."))
        if "index.html" not in fs:
            continue
        with open(os.path.join(d, "index.html"), encoding="utf-8") as f:
            text = f.read()
        for href, inner in CARD.findall(text):
            h = H2.search(inner)
            if not h or "//" in href:
                continue
            target = os.path.normpath(os.path.join(os.path.relpath(d, root), href)).replace(os.sep, "/")
            if target.startswith(".."):
                continue
            name = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", h.group(1)))).strip()
            if name and target != ".":
                names.setdefault(target, name)
    return names


def page_label(rel, text, names, nav, where):
    """#1831 a page's menu name: its hub card's name, else its <title> without the site suffix; the root is nav.root_label."""
    if not rel:
        return nav["root_label"]
    if rel in names:
        return names[rel]
    t = title_of(text, where)
    suffix = nav.get("title_suffix", "")
    return t[: -len(suffix)].strip() if suffix and t.endswith(suffix) else t


def tree(root, pin):
    """The page declaration of the index.html files under root (a source_dir): #1831 FLAT under the Chronos topic: the repo's root page
    first, then its sections in order, each with its own sub-pages nested (the repo's hierarchy below the first level)."""
    nav = pin["nav"]
    names = card_names(root)

    def node(rel):
        d = os.path.join(root, rel)
        page = os.path.join(d, "index.html")
        with open(page, encoding="utf-8") as f:
            label = page_label(rel, f.read(), names, nav, os.path.join(pin["source_dir"], rel, "index.html"))
        nid = nav["id_prefix"] + ("." + seg_id(os.path.basename(rel)) if rel else "")
        o = {"id": nid, "label": label, "icon": nav["icons"].get(rel, nav["default_icon"]),
             "asset": "/".join(x for x in (pin["source_dir"], rel, "index.html") if x)}
        kids = []
        for n in sorted(os.listdir(d), key=natural):
            if n.startswith(".") or not os.path.isdir(os.path.join(d, n)):
                continue
            sub = "/".join(x for x in (rel, n) if x)
            if os.path.isfile(os.path.join(root, sub, "index.html")):
                kids.append(node(sub))
            elif any("index.html" in fs for _, _, fs in os.walk(os.path.join(root, sub))):
                die("%s holds pages but no index.html of its own: the hierarchy would skip a level" % sub)
        if kids:
            o["pages"] = kids
        return o

    if not os.path.isfile(os.path.join(root, "index.html")):
        die("%s/index.html is missing" % pin["source_dir"])
    top = node("")
    out = [top] + top.pop("pages", [])
    ids = [p["id"] for p in flat(out)]
    if len(ids) != len(set(ids)):
        die("two Chronos pages derive the same id: %s" % sorted({i for i in ids if ids.count(i) > 1}))
    return out


def flat(pages):
    return [x for p in pages for x in [p] + flat(p.get("pages", []))]


# ── the vendored files and the HTML rewrite ──────────────────────────────
def font_css(url, pin, files, sums, repin):
    """The local stylesheet answering one Google Fonts css2 URL, from the pinned @fontsource files."""
    fonts = pin["fonts"]
    q = html.unescape(url)[len(fonts["match_prefix"]):]
    faces, names = [], []
    for part in q.split("&"):
        if not part.startswith("family="):
            continue
        spec = part[len("family="):].replace("+", " ")
        fam, _, axes = spec.partition(":")
        f = fonts["families"].get(fam)
        if not f:
            die("a page asks Google Fonts for %r, which tools/chronos-pin.json fonts.families does not pin" % fam)
        weights = [w for w in axes.split("@", 1)[1].split(";")] if "@" in axes else ["400"]
        names.append(f["slug"])
        for w in weights:
            rel = "vendor/fonts/files/%s-latin-%s-normal.woff2" % (f["slug"], w)
            if rel not in files:
                files[rel] = vendored(rel, fonts["url"].format(slug=f["slug"], version=f["version"], weight=w), sums, repin)
            faces.append("@font-face{font-family:'%s';font-style:normal;font-display:swap;font-weight:%s;src:url(files/%s) format('woff2')}"
                         % (fam, w, os.path.basename(rel)))
    css = "/* %s\n   %s -> @fontsource (%s) */\n%s\n" % (HEADER, url, fonts["license"], "\n".join(faces))
    rel = "vendor/fonts/%s.css" % "_".join(names)
    files[rel] = css.encode()
    return rel


def vendored(rel, url, sums, repin):
    data = fetch(url)
    h = sha(data)
    if repin:
        sums[rel] = h
    elif sums.get(rel) != h:
        die("%s from %s hashes %s, pinned %s (re-pin with --pin if the change is wanted)" % (rel, url, h, sums.get(rel)))
    return data


def rewrite(text, pin, files, sums, repin, where, rewrites=None):
    """#1830 [rewrites] collects every URL -> served path replaced here, for the app's runtime copy (runtime.json)."""
    base = pin["serve_path"]
    rw = rewrites if rewrites is not None else {}
    text = HINT.sub("", text)
    for v in pin["vendor"]:
        for q in ('"', "'"):
            if q + v["match"] + q in text:
                for f in v["files"]:
                    if f["path"] not in files:
                        files[f["path"]] = vendored(f["path"], f["url"], sums, repin)
                text = text.replace(q + v["match"] + q, q + base + v["rewrite"] + q)
                rw[v["match"]] = base + v["rewrite"]
    for m in sorted(set(re.findall(r"""["'](%s[^"']*)["']""" % re.escape(pin["fonts"]["match_prefix"]), text))):
        served = base + font_css(m, pin, files, sums, repin)
        text = text.replace(m, served)
        rw[m] = served
    if LOADS.search(text) or CSS_URL.search(text):
        bad = (LOADS.search(text) or CSS_URL.search(text)).group(0)
        die("%s still loads from the network after the rewrite (%s...): add the URL to tools/chronos-pin.json vendor" % (where, bad[:120]))
    return text


def baked_dirs(pin):
    """#1857 the repo folders baked into the APK: the Chronos source dir, then each project's."""
    return [pin["source_dir"]] + [p["source_dir"] for p in pin.get("projects", [])]


def generate(pin, commit, repin=False):
    """Everything the pin makes: {path under assets_dir: bytes}, the page tree, and the vendored hashes."""
    sums = {} if repin else dict(pin.get("sha256", {}))
    work = tempfile.mkdtemp(prefix="regen-chronos-")
    try:
        checkout(pin, commit, os.path.join(work, "repo"))
        files = {}
        rewrites = {}
        # #1857 the Chronos pages and every project folder of the repo (Sacred-geo/, a sibling of Chronos/) bake the same way
        for sd in baked_dirs(pin):
            src = os.path.join(work, "repo", sd)
            if not os.path.isdir(src):
                die("%s@%s has no %s/" % (pin["repo"], commit[:8], sd))
            for d, dirs, fs in os.walk(src):
                dirs[:] = sorted(x for x in dirs if not x.startswith("."))
                for f in sorted(fs):
                    if f.startswith("."):
                        continue
                    p = os.path.join(d, f)
                    rel = "/".join([sd, os.path.relpath(p, src).replace(os.sep, "/")])
                    with open(p, "rb") as fh:
                        data = fh.read()
                    if f.endswith((".html", ".htm", ".css")):
                        data = rewrite(data.decode("utf-8"), pin, files, sums, repin, rel, rewrites).encode("utf-8")
                    files[rel] = data
        for pr in pin.get("projects", []):
            for k in ("markdown", "explorer"):
                if pr["source_dir"] + "/" + pr[k] not in files:
                    die("project %s: %s/%s is missing at the pin" % (pr["id"], pr["source_dir"], pr[k]))
        src = os.path.join(work, "repo", pin["source_dir"])
        pages = tree(src, pin)
        ds = os.path.join(work, "repo", pin["dataset"]["repo_path"])
        if not os.path.isfile(ds):
            die("%s@%s has no %s (the repo's tools/gen-wiki.py writes it)" % (pin["repo"], commit[:8], pin["dataset"]["repo_path"]))
        with open(ds, "rb") as fh:
            files[DATASET] = fh.read()
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if not repin:
        unused = sorted(set(sums) - set(files))
        if unused:
            die("pinned but no longer used by any page: %s (re-pin with --pin)" % unused)
    skipped = sorted(p for p in files if any(seg.startswith(("_", ".")) for seg in p.split("/")))
    if skipped:
        die("the Android asset packager ignores these paths (a segment starts with _ or .): %s" % skipped)
    lines = ["# Chronos pages (Cloud Wiki assets)", "", HEADER, "",
             "- source: %s@%s, %s/" % (pin["repo"], commit, pin["source_dir"]),
             "- served at: https://appassets.androidplatform.net%s (WebViewAssetLoader)" % pin["serve_path"],
             "- pages: %d (declared in build.json::ui %s > %s)" % (len(flat(pages)), pin["nav"]["section"], pin["nav"]["parent"]),
             *["- project %s: %s/ (%s = its Markdown page, %s = its web page), declared in build.json::ui %s > %s"
               % (q["id"], q["source_dir"], q["markdown"], q["explorer"], pin["nav"]["section"], q["id"]) for q in pin.get("projects", [])], "",
             "## Vendored (answered from the APK, never fetched at run time)", ""]
    for v in pin["vendor"]:
        if any(f["path"] in files for f in v["files"]):
            lines.append("- %s, %s: %s" % (v["name"], v["license"], v["match"]))
    fonts_used = sorted(p for p in files if p.startswith("vendor/fonts/") and p.endswith(".css"))
    if fonts_used:
        lines.append("- Google Fonts css2 answered from @fontsource, %s: %s" % (pin["fonts"]["license"], ", ".join(os.path.basename(p) for p in fonts_used)))
    files["GENERATED.md"] = ("\n".join(lines) + "\n").encode()
    # #1830 the app clones the repo at RUN TIME (read-only) and serves the clone; this is what it needs to do that the same way
    # this tool does: where the repo is, how page ids are derived, which CDN URLs are answered from vendor/, and the refresh modes.
    # The baked pages above stay as the first-run / offline fallback until the first clone lands.
    nav = pin["nav"]
    runtime = {
        "_doc": HEADER + " #1830 read by the app (ChronosRepo): clone url@ref shallow into its own storage, never commit; "
                "serve source_dir from the clone; replace each `rewrites` URL in a page by its served path; refresh per `modes`.",
        "repo": pin["repo"], "url": pin["url"], "ref": pin["ref"], "baked_commit": commit,
        "source_dir": pin["source_dir"], "serve_path": pin["serve_path"],
        "projects": [{k: q[k] for k in ("id", "source_dir", "markdown", "explorer")} for q in pin.get("projects", [])],
        "dataset": pin["dataset"]["repo_path"],
        "nav": {"id_prefix": nav["id_prefix"], "icons": nav["icons"], "default_icon": nav["default_icon"],
                "root_label": nav["root_label"], "title_suffix": nav.get("title_suffix", "")},
        "rewrites": [{"match": k, "served": rewrites[k]} for k in sorted(rewrites)],
        "refresh": pin["runtime"]["refresh"],
    }
    files["runtime.json"] = (json.dumps(runtime, indent=2, ensure_ascii=False) + "\n").encode()
    menu_problems(json.loads(files[DATASET].decode("utf-8")), pin, die)
    return files, pages, dict(sorted(sums.items()))


# ── #1867 the wiki dataset and the side menu, from the repo's generated wiki.json ──────────────────────────────
DATASET = "\0dataset"  # the key of the dataset in generate()'s files: written to dataset.fleet_path, not under assets_dir


def fleet_path(pin):
    return os.path.normpath(os.path.join(APP, pin["dataset"]["fleet_path"]))


def menu_problems(data, pin, fail):
    """The repo's menu fits the pin: Chronos is a topic with a site at source_dir, each pinned project is a project at its folder."""
    entries = [c for m in data.get("menu", []) for c in [m] + m.get("children", [])]
    by = {e["id"]: e for e in entries}
    ch = by.get(pin["nav"]["parent"])
    if not ch or ch.get("kind") != "topic" or not ch.get("site") or ch.get("path") != pin["source_dir"]:
        fail("the repo's menu has no topic %r with a site at %s (the pin's source_dir)" % (pin["nav"]["parent"], pin["source_dir"]))
    for q in pin.get("projects", []):
        e = by.get(q["id"])
        if not e or e.get("kind") != "project" or (e.get("path"), e.get("markdown"), e.get("explorer")) != (q["source_dir"], q["markdown"], q["explorer"]):
            fail("the repo's menu has no project %r at %s with %s and %s (the pin's projects)" % (q["id"], q["source_dir"], q["markdown"], q["explorer"]))


def menu_decl(data, pages):
    """build.json::ui wiki `pages` and `groups` from the repo's menu; [pages] is the Chronos simulator tree."""
    out, groups = [], []
    for parent in data["menu"]:
        groups.append({"id": parent["id"], "label": parent["label"], "icon": parent["icon"], "pages": [c["id"] for c in parent["children"]]})
        for c in parent["children"]:
            o = {"id": c["id"], "label": c["label"], "icon": c["icon"]}
            if c["kind"] == "hub":
                o["pages"] = [{"id": t["id"], "label": t["label"], "icon": t["icon"]} for t in c["children"]]
            elif c["kind"] == "topic" and c.get("site"):
                o["pages"] = pages
            elif c["kind"] == "project":
                o["project"] = c["path"]
            out.append(o)
    return out, groups


def declared_wiki(bj, pin):
    sec = next((s for s in bj["ui"]["sections"] if s["id"] == pin["nav"]["section"]), None)
    if sec is None:
        die("build.json::ui has no section %r" % pin["nav"]["section"])
    return sec


def declared_parent(bj, pin):
    nav = pin["nav"]
    sec = next((s for s in bj["ui"]["sections"] if s["id"] == nav["section"]), None)
    if sec is None:
        die("build.json::ui has no section %r" % nav["section"])
    par = next((p for p in sec["pages"] if p["id"] == nav["parent"]), None)
    if par is None:
        die("build.json::ui section %r has no page %r" % (nav["section"], nav["parent"]))
    return par


def project_problems(bj, pin, have):
    """#1857 each pinned project is declared as a wiki page of its id carrying `project` = its source dir, and its two files are baked."""
    bad = []
    sec = next((x for x in bj["ui"]["sections"] if x["id"] == pin["nav"]["section"]), {"pages": []})
    for q in pin.get("projects", []):
        pg = next((x for x in sec["pages"] if x["id"] == q["id"]), None)
        if pg is None:
            bad.append("C8 build.json::ui %s has no page %r for the pinned project %s/" % (pin["nav"]["section"], q["id"], q["source_dir"]))
        elif pg.get("project") != q["source_dir"]:
            bad.append("C8 build.json::ui page %s names project %r, the pin says %r" % (q["id"], pg.get("project"), q["source_dir"]))
        for k in ("markdown", "explorer"):
            if have is not None and q["source_dir"] + "/" + q[k] not in have:
                bad.append("C8 project %s: %s/%s is not in the APK assets" % (q["id"], q["source_dir"], q[k]))
    return bad


def on_disk(root):
    out = {}
    if not os.path.isdir(root):
        return out
    for d, _, fs in os.walk(root):
        for f in fs:
            p = os.path.join(d, f)
            with open(p, "rb") as fh:
                out[os.path.relpath(p, root).replace(os.sep, "/")] = fh.read()
    return out


def write(pin, files, pages):
    root = os.path.join(APP, pin["assets_dir"])
    if os.path.isdir(root):
        shutil.rmtree(root)
    for rel, data in files.items():
        if rel == DATASET:
            with open(fleet_path(pin), "wb") as f:
                f.write(data)
            continue
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
    bj = load_json(BUILD)
    sec = declared_wiki(bj, pin)
    sec["pages"], sec["groups"] = menu_decl(json.loads(files[DATASET].decode("utf-8")), pages)
    dump_json(BUILD, bj)
    print("regen-chronos: %d files, %d pages from %s@%s" % (len(files), len(flat(pages)), pin["repo"], pin["commit"][:8]))


def check(pin):
    files, pages, _ = generate(pin, pin["commit"])
    bad = []
    have = on_disk(os.path.join(APP, pin["assets_dir"]))
    ds = files.pop(DATASET)
    with open(fleet_path(pin), "rb") as fh:
        if fh.read() != ds:
            bad.append("%s is not %s@%s %s byte for byte" % (pin["dataset"]["fleet_path"], pin["repo"], pin["commit"][:8], pin["dataset"]["repo_path"]))
    sec = declared_wiki(load_json(BUILD), pin)
    if (sec.get("pages"), sec.get("groups")) != menu_decl(json.loads(ds.decode("utf-8")), pages):
        bad.append("build.json::ui %s pages and groups are not the repo's menu at the pin" % pin["nav"]["section"])
    for rel in sorted(set(files) | set(have)):
        if rel not in have:
            bad.append("missing from the APK assets: " + rel)
        elif rel not in files:
            bad.append("in the APK assets but not made by the pin: " + rel)
        elif have[rel] != files[rel]:
            bad.append("differs from %s@%s: %s" % (pin["repo"], pin["commit"][:8], rel))
    if declared_parent(load_json(BUILD), pin).get("pages") != pages:
        bad.append("build.json::ui %s > %s pages are not the repo's page tree at the pin" % (pin["nav"]["section"], pin["nav"]["parent"]))
    bad += project_problems(load_json(BUILD), pin, have)
    # the repo moving on is news, not drift: the pin is what ships until someone re-pins
    try:
        tip = resolve(pin, pin["ref"])
        if tip != pin["commit"]:
            work = tempfile.mkdtemp(prefix="regen-chronos-tip-")
            try:
                git("init", "-q", work)
                git("fetch", "-q", "--depth", "1", pin["url"], tip, cwd=work)
                git("fetch", "-q", "--depth", "1", pin["url"], pin["commit"], cwd=work)
                changed = subprocess.run(["git", "diff", "--quiet", pin["commit"], tip, "--", *baked_dirs(pin)], cwd=work).returncode != 0
            finally:
                shutil.rmtree(work, ignore_errors=True)
            if changed:
                print("::warning::%s %s moved to %s and changed %s/ since the pin %s: re-pin with tools/regen-chronos.py --pin %s"
                      % (pin["repo"], pin["ref"], tip[:8], pin["source_dir"], pin["commit"][:8], pin["ref"]))
            else:
                print("regen-chronos: %s %s is at %s; %s/ is unchanged since the pin" % (pin["repo"], pin["ref"], tip[:8], pin["source_dir"]))
    except SystemExit:
        print("::warning::could not compare the pin with %s %s" % (pin["repo"], pin["ref"]))
    for b in bad:
        print("DRIFT " + b)
    if bad:
        print("FIX: python3 ac_cloud-wiki/tools/regen-chronos.py   (never edit the generated assets by hand)")
        return 1
    print("regen-chronos --check: %d files and %d pages equal %s@%s" % (len(files), len(flat(pages)), pin["repo"], pin["commit"][:8]))
    return 0


def guard(pin):
    """Offline: the committed tree, the pin hashes and build.json agree. Prints FAIL lines; 1 on any."""
    root = os.path.join(APP, pin["assets_dir"])
    bad = []
    have = on_disk(root)
    if not have:
        print("FAIL C1 %s holds no Chronos assets" % pin["assets_dir"])
        return 1
    src = os.path.join(root, pin["source_dir"])
    try:
        derived = tree(src, pin)
    except SystemExit:
        print("FAIL C1 the committed Chronos assets do not form a page tree")
        return 1
    declared = declared_parent(load_json(BUILD), pin).get("pages")
    if declared != derived:
        dids = [p["id"] for p in flat(declared or [])]
        tids = [p["id"] for p in flat(derived)]
        if dids != tids:
            bad.append("C1 build.json::ui chronos pages %s are not the assets' page tree %s" % (dids, tids))
        else:
            bad.append("C1 build.json::ui chronos pages carry other labels, icons, assets or nesting than the assets' page tree")
    for p in flat(declared or []):
        if not p.get("asset") or p["asset"] not in have:
            bad.append("C1 page %s names asset %r, which is not in %s" % (p.get("id"), p.get("asset"), pin["assets_dir"]))
    for rel, h in pin.get("sha256", {}).items():
        if rel not in have:
            bad.append("C2 pinned vendored file %s is missing" % rel)
        elif sha(have[rel]) != h:
            bad.append("C2 vendored file %s does not hash to its pin" % rel)
    for rel in have:
        if rel.startswith("vendor/") and not (rel.startswith("vendor/fonts/") and rel.endswith(".css")) and rel not in pin.get("sha256", {}):
            bad.append("C2 vendored file %s has no sha256 in the pin" % rel)
        if rel.endswith((".html", ".htm", ".css")):
            t = have[rel].decode("utf-8", errors="replace")
            if LOADS.search(t) or CSS_URL.search(t):
                bad.append("C2 %s loads from the network" % rel)
    for rel in have:
        # aapt's default ignoreAssetsPattern drops `<dir>_*` directories and dot files: such a path would be committed but never packaged
        if any(seg.startswith(("_", ".")) for seg in rel.split("/")):
            bad.append("C2 %s has a path segment the Android asset packager ignores (leading _ or .): it would be missing from the APK" % rel)
    bad += project_problems(load_json(BUILD), pin, have)
    # #1867 the side menu is the repo's menu: build.json::ui wiki pages and groups are what the committed dataset's `menu` makes
    try:
        with open(fleet_path(pin), encoding="utf-8") as fh:
            data = json.load(fh)
        menu_problems(data, pin, lambda m: bad.append("C9 " + m))
        sec = declared_wiki(load_json(BUILD), pin)
        want_pages, want_groups = menu_decl(data, derived)
        if sec.get("groups") != want_groups:
            bad.append("C9 build.json::ui wiki groups %s are not the repo's menu parents %s" % ([g.get("id") for g in sec.get("groups", [])], [g["id"] for g in want_groups]))
        if sec.get("pages") != want_pages:
            bad.append("C9 build.json::ui wiki pages are not the repo's menu (hubs > topics, Chronos, projects): %s" % sorted(
                {p.get("id") for p in sec.get("pages", [])} ^ {p["id"] for p in want_pages}) )
    except (OSError, ValueError, KeyError) as e:
        bad.append("C9 the dataset %s cannot be read as the repo's menu: %s" % (pin["dataset"]["fleet_path"], e))
    if HEADER not in have.get("GENERATED.md", b"").decode():
        bad.append("C3 GENERATED.md is missing or does not carry the DO NOT EDIT header")
    elif pin["commit"] not in have["GENERATED.md"].decode():
        bad.append("C3 GENERATED.md does not name the pinned commit %s" % pin["commit"][:8])
    for b in bad:
        print("FAIL " + b)
    return 1 if bad else 0


def main(argv):
    pin = load_json(PIN)
    if argv[:1] == ["--check"]:
        return check(pin)
    if argv[:1] == ["--guard"]:
        return guard(pin)
    if argv[:1] == ["--tree"]:
        print(json.dumps(tree(os.path.join(APP, pin["assets_dir"], pin["source_dir"]), pin), indent=2))
        return 0
    if argv[:1] == ["--pin"]:
        if len(argv) < 2:
            die("--pin needs a sha or a ref")
        pin["commit"] = resolve(pin, argv[1])
        files, pages, sums = generate(pin, pin["commit"], repin=True)
        pin["sha256"] = sums
        dump_json(PIN, pin)
        write(pin, files, pages)
        return 0
    if argv:
        die("unknown arguments %s (see the docstring)" % argv)
    files, pages, _ = generate(pin, pin["commit"])
    write(pin, files, pages)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
