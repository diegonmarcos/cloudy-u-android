#!/usr/bin/env python3
"""#1934 generates the control | command | test id | PASS/FAIL table from the declaration (ui.git_control_sheet) and test/fixtures/git-control-test-map.json.
Fails (exit 1) when a declared control has no row, or a referenced test class / method does not exist in the repo's test sources. Usage: gen... <repo root> [--write]"""
import json, os, re, sys
root = sys.argv[1]; write = "--write" in sys.argv
def opt(k, d=""):
    return sys.argv[sys.argv.index(k) + 1] if k in sys.argv else d
junit_root = opt("--junit-root"); observed_out = opt("--out"); walk_path = opt("--walk"); run_id = opt("--run-id"); head_sha = opt("--sha")
app = os.path.join(root, "ac_cloud-drive")
d = json.load(open(os.path.join(app, "build.json")))["ui"]["git_control_sheet"]
m = json.load(open(os.path.join(app, "test", "fixtures", "git-control-test-map.json")))
src = ""
for top in ("ac_cloud-drive/app/src/test", "ab_cloud-libs-shared/libs/git-core/src/test", "ab_cloud-libs-shared/libs/git-ui/src/test", "ab_cloud-libs-shared/libs/git-repos/src/test"):
    for base, _, files in os.walk(os.path.join(root, top)):
        for f in files:
            if f.endswith("Test.kt"): src += open(os.path.join(base, f), errors="ignore").read() + "\n"
import glob
observed = {}   # (class, method) -> "PASS" | "FAIL"
if junit_root:
    import xml.etree.ElementTree as ET
    for f in glob.glob(os.path.join(junit_root, "**", "TEST-*.xml"), recursive=True):
        try: tree = ET.parse(f)
        except Exception: continue
        for tc in tree.getroot().iter("testcase"):
            cls = tc.get("classname", "").split(".")[-1]; name = tc.get("name", "")
            bad = tc.find("failure") is not None or tc.find("error") is not None
            observed[(cls, name)] = "FAIL" if bad or observed.get((cls, name)) == "FAIL" else "PASS"
def observe(t):
    cls, _, meth = t.partition("#")
    rs = [v for (c, n), v in observed.items() if c == cls and (not meth or meth in n)]
    return "FAIL" if (not rs or "FAIL" in rs) else "PASS"
walk = {}
if walk_path and os.path.exists(walk_path):
    for l in open(walk_path):
        c = l.rstrip("\n").split("\t")
        if len(c) >= 4: walk[c[1]] = "PASS" if c[3] in ("tapped", "shown") else "FAIL"
def exists(t):
    cls, _, meth = t.partition("#")
    if not re.search(r"\bclass %s\b" % re.escape(cls), src): return False
    return not meth or re.search(r"fun (`[^`]*%s[^`]*`|%s)\(" % (re.escape(meth), re.escape(meth)), src) is not None
rows = []; bad = 0
reasons = d["reasons"]
def add(scope, c, gid):
    global bad
    ov = m["controls"].get(c["id"]); g = m["groups"].get(gid) or m["groups"].get(gid.split(".")[0])
    r = ov or g
    if r is None: print("no row for", scope, c["id"], gid); bad = 1; return
    tests = r.get("tests", [])
    for t in tests:
        if not exists(t): print("referenced test does not exist:", t, "(", c["id"], ")"); bad = 1
    disabled = c.get("disabled") or r.get("disabled")
    if disabled: status = "DISABLED"; note = reasons.get(c.get("reason", ""), "") or "the in-process engine (JGit) has no recursive submodule support"
    elif not tests: status = "FAIL"; note = "GAP: " + r.get("gap", "no executed test")
    else: status = "PASS"; note = r.get("note", "")
    if c.get("needs_clone") and status == "PASS": note = (note + "; " if note else "") + "disabled with a reason when not cloned"
    obs = "-"
    if junit_root:
        obs = "DISABLED" if status == "DISABLED" else ("FAIL" if not tests else ("PASS" if all(observe(t) == "PASS" for t in tests) else "FAIL"))
    emu = walk.get(c["id"], "not run") if walk_path else "-"
    rows.append((scope, c["id"], c["label"], r["command"], "; ".join(tests) or "-", status, note, obs, emu))
h = d["header"]
for c in h["actions"] + [h["refresh"], h["close"], h["banner"], h["clone_now"]] + h["fields"]: add("header", c, "hd")
for tag, tabs in (("repo", d["tabs"]), ("all", d["bulk"]["tabs"])):
    for t in tabs:
        for g in t["groups"]:
            for c in g["controls"]: add(tag + "/" + t["id"], c, g["id"])
n = len(rows); p = sum(1 for r in rows if r[5] == "PASS"); f = sum(1 for r in rows if r[5] == "FAIL"); x = sum(1 for r in rows if r[5] == "DISABLED")
src_label = "observed in run %s at %s" % (run_id or "?", head_sha or "?") if junit_root else "declaration level"
out = ["# Git control sheet: control | command | test id | PASS/FAIL", "",
       "Generated by `ac_cloud-drive/test/gen-git-control-sheet-results.py` from the declaration (`ui.git_control_sheet`) and `test/fixtures/git-control-test-map.json`; `test-drive-git-control-sheet-results.sh` fails when this file is stale.",
       "PASS = every referenced test exists and runs in the fatal steps of Ship -> Cloud Drive (a red Ship run makes this table stale). FAIL = a GAP (no executed test yet). DISABLED = shown disabled with its reason.", "",
       "Disabled combination (not a control of its own): Winner with Rebase, Sync Now is disabled with `reasons.rebase_winner`; executed: PlanExecutorFastTest#aWinnerWithRebaseIsRefusedBeforeAnythingRuns.", "", "Totals: %d controls, %d PASS, %d FAIL, %d DISABLED" % (n, p, f, x), "",
       "THIS FILE (" + src_label + "): the committed copy is the declaration-level table (PASS = referenced tests exist). The observed table (JVM column = the test ids' real JUnit results, emulator column = the walk) is generated by the Ship job as the run artifact git-control-sheet-results-observed.", ""]
if junit_root:
    out += ["Observed JVM: %d PASS, %d FAIL, %d DISABLED; emulator: %d PASS, %d FAIL, %d not run" % (sum(1 for r in rows if r[7] == "PASS"), sum(1 for r in rows if r[7] == "FAIL"), sum(1 for r in rows if r[7] == "DISABLED"), sum(1 for r in rows if r[8] == "PASS"), sum(1 for r in rows if r[8] == "FAIL"), sum(1 for r in rows if r[8] == "not run")), ""]
out += ["| scope | control | label | command | test id | declared | note | JVM observed | emulator |", "|---|---|---|---|---|---|---|---|---|"]
for r in rows: out.append("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |")
text = "\n".join(out) + "\n"
path = observed_out or os.path.join(app, "test", "results", "git-control-sheet-results.md")
if observed_out or write: open(path, "w").write(text)
if not (observed_out or write) and (not os.path.exists(path) or open(path).read() != text):
    print("the committed result table is stale: run gen-git-control-sheet-results.py --write"); bad = 1
print("results: %d controls, %d PASS, %d FAIL, %d DISABLED" % (n, p, f, x))
sys.exit(bad)
