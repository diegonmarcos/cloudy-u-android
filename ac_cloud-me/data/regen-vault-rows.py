#!/usr/bin/env python3
"""Tasks rows (#1398): the multi-row sub-page bar of Tasks, derived from the root layout of the private notes vault
diegonmarcos/cloud-me-pvt-notes (flat since faf97d2: every folder sits at the root, the hierarchy is its number).

  data/repos/vault-rows.snapshot.txt  SNAPSHOT: the vault's numbered root folders (lines ending in "/") and the notes
                                      directly inside them (`<folder>/<note>.md`), sorted; never note content
  data/repos/vault-rows.json          GENERATED from the snapshot + build.json::ui.vault_rows (DO NOT EDIT), shipped as
                                      an asset; app/build.gradle bakes its chips into ui.sections[tasks] as page groups

  ./data/regen-vault-rows.py                 render vault-rows.json
  ./data/regen-vault-rows.py --check         exit 1 if vault-rows.json is not the render (drift)
  ./data/regen-vault-rows.py --refresh       re-read the vault through `gh api` (needs a token that reads the private repo)

Rules (no folder name is typed anywhere): a folder's NUMBER is its leading dotted digits (`1.1.10.1_x` -> 1.1.10.1); its
ANCHOR is the nearest ancestor number that exists as a folder (1.1.10.1 -> 1.1 when 1.1.10 does not exist), else its
immediate parent number (00.1 -> 00). A row (build.json::ui.vault_rows.rows[]: id, label, under[], sub) holds as chips
every folder whose anchor is in `under`, except the row roots (each row's `root` folder); chips are in natural number
order. A `sub` row also lists, per chip, the folders anchored on that chip (Library: 2.x.y). A label is the folder
name without its number and without the surrounding underscores (`1.10___42___` -> `42`, `_` -> space).
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "diegonmarcos/cloud-me-pvt-notes"
SNAP = os.path.join(HERE, "repos", "vault-rows.snapshot.txt")
OUT = os.path.join(HERE, "repos", "vault-rows.json")
BUILD = os.path.join(HERE, "..", "build.json")
NUM = re.compile(r"^(\d+(?:\.\d+)*)_(.*)$")


def number(name):
    m = NUM.match(name)
    return m.group(1) if m else None


def label(name):
    m = NUM.match(name)
    rest = m.group(2) if m else name
    return re.sub(r"\s+", " ", rest.strip("_").replace("_", " ")).strip()


def nat(num):
    return [int(p) for p in num.split(".")] + [-len(num)]  # 00 sorts before 0 before 1; 1.9 before 1.10


def parent(num):
    return num.rsplit(".", 1)[0] if "." in num else None


def anchor(num, have):
    p = parent(num)
    while p is not None:
        if p in have:
            return p
        p = parent(p)
    return parent(num)


def page_id(num):
    return "v" + num.replace(".", "-")


def render(lines, decl):
    folders = sorted({l[:-1] for l in lines if l.endswith("/") and number(l[:-1]) is not None}, key=lambda f: nat(number(f)))
    notes = {}
    for l in lines:
        if not l.endswith("/") and "/" in l and l.endswith(".md"):
            d, f = l.split("/", 1)
            if "/" not in f:
                notes.setdefault(d, []).append(f[:-3])
    have = {number(f) for f in folders}
    roots = {r["root"] for r in decl["rows"]}
    chip_of = {}

    def item(f):
        return {"page": page_id(number(f)), "num": number(f), "label": label(f), "path": f,
                "notes": sorted(notes.get(f, []), key=str.lower)}

    rows = []
    for r in decl["rows"]:
        under = set(r["under"])
        chips = [item(f) for f in folders if f not in roots and anchor(number(f), have) in under]
        for c in chips:
            chip_of[c["path"]] = r["id"]
        rows.append({"id": r["id"], "label": r["label"], "root": r["root"], "chips": chips})
    for r, d in zip(rows, decl["rows"]):
        if d.get("sub"):
            for c in r["chips"]:
                c["children"] = [item(f) for f in folders
                                 if f not in roots and f not in chip_of and anchor(number(f), have) == c["num"]]
    return {"_generated": "GENERATED by data/regen-vault-rows.py from data/repos/vault-rows.snapshot.txt and "
                          "build.json::ui.vault_rows — DO NOT EDIT. Refresh: ./data/regen-vault-rows.py --refresh",
            "_schema": "cloud-me-vault-rows/v1", "source": REPO, "rows": rows}


def text(t):
    return json.dumps(t, indent=2, ensure_ascii=False) + "\n"


def live():
    r = subprocess.run(["gh", "api", f"repos/{REPO}/git/trees/main?recursive=1", "--jq",
                        '.tree[] | if .type=="tree" then .path+"/" else .path end'], capture_output=True, text=True)
    if r.returncode != 0:
        return None
    out = []
    for l in r.stdout.splitlines():
        top = l.split("/", 1)[0]
        if number(top) is None:
            continue
        if l.endswith("/") and l.count("/") == 1:
            out.append(l)
        elif l.endswith(".md") and l.count("/") == 1:
            out.append(l)
    return sorted(out)


def main(argv):
    if "--refresh" in argv:
        now = live()
        if now is None:
            print(f"cannot read {REPO} through gh api", file=sys.stderr)
            return 2
        open(SNAP, "w", encoding="utf-8").write("\n".join(now) + "\n")
    lines = [l.rstrip("\n") for l in open(SNAP, encoding="utf-8") if l.strip()]
    decl = json.load(open(BUILD, encoding="utf-8"))["ui"]["vault_rows"]
    want = text(render(lines, decl))
    have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in argv:
        if have != want:
            print("DRIFT: data/repos/vault-rows.json is not the render of its snapshot — run ./data/regen-vault-rows.py")
            return 1
        print("vault-rows.json is current with its snapshot")
        return 0
    if have != want:
        open(OUT, "w", encoding="utf-8").write(want)
    print("wrote" if have != want else "unchanged", "data/repos/vault-rows.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
