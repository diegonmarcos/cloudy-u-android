#!/usr/bin/env python3
"""#1918 Proj emoji and banners: derive data/web/me-proj-emoji.json from the Linktree data (cloud-me-pub-profiles-_lnktree
Lnktree/linktree/src/data/areas.json: each area/project `icon`, each area `banner`, the banner files served by linktree.diegonmarcos.com).
A Proj page with no Linktree counterpart (Home, SuperApp, BioMed, the Wiki leaves, the Wiki group) takes a declared fallback, marked `fallback`.
  regen-proj-emoji.py          rewrite the table (and the label prefix of the Proj pages in build.json)
  regen-proj-emoji.py --check  fail when the table differs from the Linktree data (needs the _lnktree repo beside this clone, or --sot DIR)
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = os.path.join(HERE, "web", "me-proj-emoji.json")
ORIGIN = "https://linktree.diegonmarcos.com/"
# page id -> (Linktree area code, project code or None). A None area = the declared fallback below.
GROUPS = {"pj-unix": "1", "pj-cg": "2", "pj-capital": "3", "pj-hardtech": "4", "pj-projects": "6", "pj-lecole42": "5"}
LEAVES = {"pj-unix-cloudy": "1.1", "pj-unix-cloudme": "1.2", "pj-cg-omniverse": "2.1", "pj-cg-zirkusverse": "2.2", "pj-capital-cb": "3.1", "pj-capital-pm": "3.2",
          "pj-capital-finterm": "3.3", "pj-hardtech-deepxtech": "4.2", "pj-hardtech-cad": "4.3", "pj-projects-endeavours": "6.1", "pj-projects-duckpeng": "6.2",
          "pj-lecole42-algo": "5.1", "pj-lecole42-graphic": "5.2", "pj-lecole42-system": "5.3", "pj-lecole42-mylibs": "5.4", "pj-lecole42-curriculum": "5.5",
          "pj-lecole42-agentic": "5.6", "pj-lecole42-datascience": "5.7", "pj-lecole42-machinelearning": "5.8", "pj-lecole42-cyberwarfare": "5.9", "pj-lecole42-dev": "5.10"}
FALLBACK = {"pj-home": "\U0001F3E0", "pj-wiki": "\U0001F4D6", "pj-repos": None, "pj-unix-superapp": "\U0001F4F1", "pj-hardtech-biomed": "\U0001F48A",
            "pj-wiki-modernsc": "\U0001F52D", "pj-wiki-arcanum": "\U0001F52E", "pj-wiki-projects": "\U0001F5C2️"}
FALLBACK_BANNER = {"pj-wiki": "public/images/banners/suite.gif"}
def sot_root():
    a = sys.argv
    if "--sot" in a: return a[a.index("--sot") + 1]
    return os.environ.get("ME_SOT_DIR", os.path.abspath(os.path.join(HERE, "..", "..", "..")))
def derive(areas_json):
    areas = {a["code"]: a for a in areas_json["areas"]}
    direct = {d["field"]: d for d in areas_json["direct"]}
    emoji, src, banners = {}, {}, {}
    for g, c in GROUPS.items():
        emoji[g] = areas[c]["icon"]; src[g] = "areas/%s/icon" % c; banners[g] = {"path": areas[c]["banner"], "source": "areas/%s/banner" % c}
    for l, c in LEAVES.items():
        p = {p["code"]: p for p in areas[c.split(".")[0]]["projects"]}[c]
        emoji[l] = p["icon"]; src[l] = "areas/%s/projects/%s/icon" % (c.split(".")[0], c)
    emoji["pj-repos"] = direct["Repos"]["icon"]; src["pj-repos"] = "direct/Repos/icon"
    banners["pj-repos"] = {"path": direct["Repos"]["card"]["image"]["src"], "source": "direct/Repos/card/image"}
    for k, v in FALLBACK.items():
        if v: emoji[k] = v; src[k] = "fallback"
    for k, v in FALLBACK_BANNER.items(): banners[k] = {"path": v, "source": "fallback"}
    # #1937 every banner is BUNDLED (data/web/banners/<file>, copied from the Linktree site's public/images/banners): the app draws the asset, never the network;
    # `url` stays as the declared origin of the file and as the refresh source, never the only source.
    for b in banners.values(): b["url"] = ORIGIN + b["path"]; b["asset"] = "banners/" + os.path.basename(b["path"])
    return emoji, src, banners
def main():
    path = os.path.join(sot_root(), "cloud-me-pub-profiles-_lnktree/Lnktree/linktree/src/data/areas.json")
    emoji, src, banners = derive(json.load(open(path, encoding="utf-8")))
    if "--check" not in sys.argv:   # copy the banner files next to the table (the Linktree repo is public; so is this one)
        pub = os.path.join(sot_root(), "cloud-me-pub-profiles-_lnktree/Lnktree/linktree/src/public/images/banners")
        import shutil
        os.makedirs(os.path.join(HERE, "web/banners"), exist_ok=True)
        for b in banners.values():
            src_f = os.path.join(pub, os.path.basename(b["path"]))
            if os.path.isfile(src_f): shutil.copyfile(src_f, os.path.join(HERE, "web", b["asset"]))
    table = {"_doc": "#1918 the emoji of every Proj page (tab label prefix, build.json ui.sections proj) and the banner of every main category (Proj Home), taken from the Linktree data "
                     "(areas.json of cloud-me-pub-profiles-_lnktree: area/project `icon`, area `banner`, banner files served from the Linktree site). `fallback` = no Linktree counterpart. "
                     "Generated by data/regen-proj-emoji.py; --check compares with the Linktree data.",
             "origin": ORIGIN, "emoji": {k: {"emoji": emoji[k], "source": src[k]} for k in emoji}, "banners": banners}
    if "--check" in sys.argv:
        old = json.load(open(TABLE, encoding="utf-8"))
        if old != table: sys.exit("me-proj-emoji.json differs from the Linktree data")
        print("me-proj-emoji: %d emoji, %d banners match" % (len(emoji), len(banners))); return
    open(TABLE, "w", encoding="utf-8").write(json.dumps(table, indent=2, ensure_ascii=False) + "\n")
    # the label prefix in build.json (text edit: the file is not round-trip stable)
    bj = os.path.join(HERE, "..", "build.json"); s = open(bj, encoding="utf-8").read()
    for pid, e in emoji.items():
        s = re.sub(r'("id": "%s",\s*"label": ")(?:[^"\w]* )?([^"]*)"' % re.escape(pid), lambda m: m.group(1) + e + " " + m.group(2) + '"', s)
    open(bj, "w", encoding="utf-8").write(s)
if __name__ == "__main__": main()
