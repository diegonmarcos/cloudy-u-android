#!/usr/bin/env python3
"""#1937 Proj > Home tile icons: one bundled vector drawable per project leaf (app/src/main/res/drawable/ic_pj_<leaf>.xml), declared in build.json as the leaf's `tile_icon`.

A project whose repository has its own app icon in this monorepo wears it (the adaptive launcher icon's background + foreground merged into one vector, from
the sibling app's res/drawable: SuperApp, Cloud-me, FinTerm: public art, this repo is public). Every other project gets a DISTINCT declared vector: a coloured
badge (the colour family of its area) holding one geometric glyph; no two share a (colour, glyph) pair, and none is the shared globe (ic_world) or link tile.
  regen-proj-icons.py          rewrite the drawables and the `tile_icon` of every Proj leaf in build.json
  regen-proj-icons.py --check  exit 1 on drift
"""
import json, math, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.abspath(os.path.join(HERE, ".."))
RES = os.path.join(APP, "app/src/main/res/drawable")
MONO = os.path.abspath(os.path.join(APP, ".."))
# leaf id -> ("app", sibling app dir) | ("glyph", colour, shape)
SPEC = {
    "pj-unix-superapp": ("app", "aa_cloud-superapp"), "pj-unix-cloudme": ("app", "ac_cloud-me"), "pj-unix-cloudy": ("glyph", "#1E88E5", "ring"),
    "pj-cg-omniverse": ("glyph", "#7E57C2", "star5"), "pj-cg-zirkusverse": ("glyph", "#7E57C2", "tri"),
    "pj-capital-cb": ("glyph", "#2E7D32", "bars"), "pj-capital-pm": ("glyph", "#2E7D32", "diamond"), "pj-capital-finterm": ("app", "ad_Capital-Stack-FinTerminal"),
    "pj-hardtech-biomed": ("glyph", "#E65100", "plus"), "pj-hardtech-cad": ("glyph", "#E65100", "hex"), "pj-hardtech-deepxtech": ("glyph", "#E65100", "star6"),
    "pj-wiki-modernsc": ("glyph", "#00897B", "ring"), "pj-wiki-arcanum": ("glyph", "#00897B", "star5"), "pj-wiki-projects": ("glyph", "#00897B", "square"),
    "pj-projects-endeavours": ("glyph", "#D81B60", "tri"), "pj-projects-duckpeng": ("glyph", "#D81B60", "circle"),
    "pj-lecole42-algo": ("glyph", "#455A64", "tri"), "pj-lecole42-graphic": ("glyph", "#455A64", "diamond"), "pj-lecole42-system": ("glyph", "#455A64", "hex"),
    "pj-lecole42-mylibs": ("glyph", "#455A64", "bars"), "pj-lecole42-curriculum": ("glyph", "#455A64", "square"), "pj-lecole42-agentic": ("glyph", "#455A64", "star5"),
    "pj-lecole42-datascience": ("glyph", "#455A64", "plus"), "pj-lecole42-machinelearning": ("glyph", "#455A64", "star6"),
    "pj-lecole42-cyberwarfare": ("glyph", "#455A64", "cross"), "pj-lecole42-dev": ("glyph", "#455A64", "ring"),
}
def poly(n, r=24.0, rot=-90.0, cx=54.0, cy=54.0):
    pts = [(cx + r * math.cos(math.radians(rot + 360.0 * i / n)), cy + r * math.sin(math.radians(rot + 360.0 * i / n))) for i in range(n)]
    return "M" + " L".join("%.2f,%.2f" % p for p in pts) + " z"
def star(n, ro=26.0, ri=11.0, cx=54.0, cy=54.0):
    pts = []
    for i in range(2 * n):
        r = ro if i % 2 == 0 else ri; a = math.radians(-90.0 + 180.0 * i / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return "M" + " L".join("%.2f,%.2f" % p for p in pts) + " z"
SHAPES = {
    "circle": "M54,30 a24,24 0 1 0 0.01,0 z",
    "ring": "M54,30 a24,24 0 1 0 0.01,0 z M54,42 a12,12 0 1 1 -0.01,0 z",
    "square": "M32,32 h44 v44 h-44 z", "tri": poly(3, 28), "diamond": poly(4, 28), "hex": poly(6, 26, 0), "star5": star(5), "star6": star(6, 27, 14),
    "plus": "M46,28 h16 v18 h18 v16 h-18 v18 h-16 v-18 h-18 v-16 h18 z",
    "bars": "M30,62 h12 v16 h-12 z M48,46 h12 v32 h-12 z M66,30 h12 v48 h-12 z",
    "cross": "M34,28 L54,48 L74,28 L80,34 L60,54 L80,74 L74,80 L54,60 L34,80 L28,74 L48,54 L28,34 z",
}
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by data/regen-proj-icons.py (#1937). Do not edit: change the table there and regenerate. -->\n'
def glyph_xml(color, shape):
    return (HEAD + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp"\n    android:viewportWidth="108" android:viewportHeight="108">\n'
            '    <path android:fillColor="%s" android:pathData="M24,6 h60 a18,18 0 0 1 18,18 v60 a18,18 0 0 1 -18,18 h-60 a18,18 0 0 1 -18,-18 v-60 a18,18 0 0 1 18,-18 z" />\n'
            '    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="%s" />\n</vector>\n') % (color, SHAPES[shape])
def inner(path):
    t = open(path, encoding="utf-8").read()
    t = re.sub(r"<\?xml[^>]*\?>\s*", "", t); t = re.sub(r"<!--.*?-->\s*", "", t, flags=re.S)
    return re.search(r"<vector[^>]*>(.*)</vector>", t, re.S).group(1).strip("\n")
def app_xml(app):
    d = os.path.join(MONO, app, "app/src/main/res/drawable")
    return (HEAD + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n    android:width="108dp" android:height="108dp"\n    android:viewportWidth="108" android:viewportHeight="108">\n'
            + inner(os.path.join(d, "ic_launcher_background.xml")) + "\n" + inner(os.path.join(d, "ic_launcher_foreground.xml")) + "\n</vector>\n")
def build():
    out = {}
    for leaf, s in SPEC.items():
        out["ic_pj_" + leaf[3:].replace("-", "_")] = app_xml(s[1]) if s[0] == "app" else glyph_xml(s[1], s[2])
    return out
def main(argv):
    out = build(); drift = []
    for name, xml in out.items():
        p = os.path.join(RES, name + ".xml")
        if (open(p, encoding="utf-8").read() if os.path.exists(p) else None) != xml:
            drift.append(name)
            if "--check" not in argv: open(p, "w", encoding="utf-8").write(xml)
    bj = os.path.join(APP, "build.json"); s = open(bj, encoding="utf-8").read(); s0 = s
    for leaf in SPEC:
        name = "ic_pj_" + leaf[3:].replace("-", "_")
        m = re.search(r'("id": "%s",\s*"label": "[^"]*",\s*"icon": "[^"]*"(?:,\s*"emoji_only": true)?)(,\s*"tile_icon": "[^"]*")?' % re.escape(leaf), s)
        if not m: sys.exit("build.json has no Proj leaf %s" % leaf)
        s = s[:m.start()] + m.group(1) + ',\n                "tile_icon": "%s"' % name + s[m.end():]
    if s != s0:
        drift.append("build.json tile_icon")
        if "--check" not in argv: open(bj, "w", encoding="utf-8").write(s)
    if "--check" in argv:
        for d in drift: print("DRIFT:", d)
        return 1 if drift else 0
    print("wrote" if drift else "unchanged", ", ".join(drift)); return 0
if __name__ == "__main__": sys.exit(main(sys.argv[1:]))
