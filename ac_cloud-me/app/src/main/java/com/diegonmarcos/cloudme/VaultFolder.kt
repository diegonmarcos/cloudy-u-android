package com.diegonmarcos.cloudme

import org.json.JSONArray
import org.json.JSONObject

/** One vault folder as a Tasks chip (#1398): its cleaned [label], its [notes] (note names, never content) and, on a `sub` row (Library), its own sub-folders. */
data class VaultFolder(val page: String, val num: String, val label: String, val path: String, val notes: List<String>, val children: List<VaultFolder>)

/** One row of the Tasks bar: Inboxes, Backlogs, RoadMaps, Library (Projects is Lnktree's Proj group, baked by app/build.gradle). */
data class VaultRow(val id: String, val label: String, val chips: List<VaultFolder>)

/**
 * #1398 the Tasks rows, read from data/repos/vault-rows.json (generated by data/regen-vault-rows.py from the notes vault's
 * folder numbers, schema cloud-me-vault-rows/v1). Pure: parse, and find the folder a chip page opens.
 */
object VaultRows {
    const val SCHEMA = "cloud-me-vault-rows/v1"

    /** A wrong schema or malformed text is no rows, never a crash. */
    fun parse(text: String): List<VaultRow> = runCatching {
        val o = JSONObject(text)
        if (o.optString("_schema") != SCHEMA) return emptyList()
        o.optJSONArray("rows").objs().map { r -> VaultRow(r.optString("id"), r.optString("label"), r.optJSONArray("chips").objs().map(::folder)) }
    }.getOrDefault(emptyList())

    private fun folder(o: JSONObject): VaultFolder = VaultFolder(o.optString("page"), o.optString("num"), o.optString("label"), o.optString("path"),
        o.optJSONArray("notes").let { a -> (0 until (a?.length() ?: 0)).map { a!!.optString(it) } }, o.optJSONArray("children").objs().map(::folder))

    private fun JSONArray?.objs(): List<JSONObject> = if (this == null) emptyList() else (0 until length()).mapNotNull { optJSONObject(it) }

    /** The chip (or a chip's sub-folder) whose vault path is [path]; null when the vault no longer has it. */
    fun find(rows: List<VaultRow>, path: String): VaultFolder? {
        fun walk(f: VaultFolder): VaultFolder? = if (f.path == path) f else f.children.firstNotNullOfOrNull(::walk)
        return rows.asSequence().flatMap { it.chips }.firstNotNullOfOrNull(::walk)
    }
}
