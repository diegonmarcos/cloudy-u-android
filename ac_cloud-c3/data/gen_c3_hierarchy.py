#!/usr/bin/env python3
"""#1495 Generate data/c3_hierarchy.json, the ONE declared hierarchy of the Cloud-C3 app, the cloudy-c3-api routes and the
cloudy-c3-mcp tools, and the OpsMap rows of the catalog pages (data/ops_maps.json maps.hier_*).

Inputs: ../build.json ui.sections (the app tree), data/c3_hierarchy_map.json (node -> route and tool patterns),
data/container_projects.json (Containers projects and Filters). Output is deterministic; `--check` exits 1 when a committed
file differs. cloudy-u-containers vendors c3_hierarchy.json (cloudy-c3-api and cloudy-c3-mcp src/code/shared/c3-hierarchy.json,
same bytes, pinned by sha256 in its tests)."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "c3_hierarchy.json")
OPS = os.path.join(HERE, "ops_maps.json")


def load(p):
    with open(os.path.join(HERE, p) if not os.path.isabs(p) else p, encoding="utf-8") as f:
        return json.load(f)


def strip(parent, cid):
    return cid[len(parent) + 1:] if cid.startswith(parent + "_") else cid


def tree(ui):
    out, ids = [], {}
    for s in ui["sections"]:
        sec = {"id": s["id"], "label": s["label"]}
        pages = {p["id"]: p for p in s.get("pages", [])}
        kids = []
        if s.get("groups"):
            for g in s["groups"]:
                gk = []
                for pid in g["pages"]:
                    gk.append({"id": pid, "label": pages[pid]["label"]})
                    ids[f"{s['id']}/{g['id']}/{pid}"] = pid
                kids.append({"id": g["id"], "label": g["label"], "children": gk})
        else:
            for p in s.get("pages", []):
                if p.get("pages"):
                    gk = []
                    for q in p["pages"]:
                        leaf = strip(p["id"], q["id"])
                        gk.append({"id": leaf, "label": q["label"]})
                        ids[f"{s['id']}/{p['id']}/{leaf}"] = q["id"]
                    kids.append({"id": p["id"], "label": p["label"], "children": gk})
                else:
                    kids.append({"id": p["id"], "label": p["label"]})
                    ids[f"{s['id']}/{p['id']}"] = p["id"]
        if not kids:
            ids[s["id"]] = s["id"]
        if kids:
            sec["children"] = kids
        out.append(sec)
    return out, ids


def leaves(nodes, prefix=""):
    for n in nodes:
        p = f"{prefix}{n['id']}"
        if n.get("children"):
            yield from leaves(n["children"], p + "/")
        else:
            yield p, n


def build():
    bj = load(os.path.join(HERE, "..", "build.json"))["ui"]
    mp = load("c3_hierarchy_map.json")
    cp = load("container_projects.json")
    secs, ids = tree(bj)
    nodes = mp["nodes"]
    base = {s: v["base"] for s, v in mp.get("scoped", {}).items()}
    # scoped sections: a project other than the base is the same data scoped by project
    want = {}
    for path, leaf in leaves(secs):
        sec = path.split("/")[0]
        parts = path.split("/")
        if sec in base and len(parts) == 3 and parts[1] != base[sec]:
            leaf["same_as"] = f"{sec}/{base[sec]}/{parts[2]}"
            if f"{sec}/{base[sec]}/{parts[2]}" not in nodes:
                raise SystemExit(f"scoped base {leaf['same_as']} has no map entry")
            continue
        if path not in nodes:
            raise SystemExit(f"tree node {path} has no entry in c3_hierarchy_map.json")
        leaf["api"], leaf["mcp"] = nodes[path]["api"], nodes[path]["mcp"]
        want[path] = 1
    extra = set(nodes) - set(want)
    if extra:
        raise SystemExit(f"c3_hierarchy_map.json names nodes the app does not declare: {sorted(extra)}")
    proj = [p["id"] for p in cp["projects"]]
    declared = [n["id"] for s in secs if s["id"] in base for n in s["children"] if n["id"] != base[s["id"]]]
    if proj != declared:
        raise SystemExit(f"container_projects.json projects {proj} differ from build.json containers pages {declared}")
    h = {
        "_doc": "GENERATED by ac_cloud-c3/data/gen_c3_hierarchy.py from build.json ui.sections + c3_hierarchy_map.json + container_projects.json (#1495). DO NOT EDIT. The one declared hierarchy of the Cloud-C3 app, the cloudy-c3-api routes (served also under /<tree path>/<legacy path>) and the cloudy-c3-mcp tools (one dispatcher c3_<section>, method <tree path below the section, dots>.<legacy tool name, dots as underscores>). Vendored byte-equal into cloudy-u-containers cloudy-c3-api and cloudy-c3-mcp (src/code/shared/c3-hierarchy.json).",
        "version": 1,
        "bottom_nav": bj["bottom_nav"],
        "sections": secs,
        "containers": {
            "default_project": cp["default"],
            "projects": [{k: p.get(k, []) if k.endswith("prefix") else p[k] for k in ("id", "label", "folder_prefix", "name_prefix")} for p in cp["projects"]],
            "name_overrides": cp.get("name_overrides", {}),
            "default_kind": cp["default_kind"],
            "filters": [{"id": k["id"], "label": k["label"], "name_suffix": k.get("name_suffix", []), "name_contains": k.get("name_contains", []), "category_prefix": k.get("category_prefix", [])} for k in cp["kinds"]],
        },
    }
    return h, ids, mp


def catalog_maps(h, ids, mp):
    by = dict(leaves(h["sections"]))
    maps = {}
    for path in mp["catalog_pages"]:
        n = by[path]
        sec = path.split("/")[0]
        rest = ".".join(path.split("/")[1:])
        api = [{"name": a, "note": f"also /{path}{a}"} for a in n["api"]]
        tools = [{"name": f"c3_{sec} {rest}.{t.replace('.', '_')}", "note": f"legacy {t}"} for t in n["mcp"]]
        secs = []
        if api:
            secs.append({"title": "cloudy-c3-api routes", "rows": api})
        if tools:
            secs.append({"title": "cloudy-c3-mcp tools", "rows": tools})
        maps["hier_" + ids[path]] = {"summary": f"{n['label']}: the API routes and MCP tools of this page, from the one hierarchy (data/c3_hierarchy.json, #1495). Old route paths and tool names stay as aliases.", "sections": secs}
    return maps


def main():
    h, ids, mp = build()
    text = json.dumps(h, indent=1, ensure_ascii=False) + "\n"
    ops = load("ops_maps.json")
    ops["maps"] = {k: v for k, v in ops["maps"].items() if not k.startswith("hier_")}
    ops["maps"].update(catalog_maps(h, ids, mp))
    if "hier_*" not in ops["_doc"]:
        ops["_doc"] += " #1495: the maps.hier_* entries are GENERATED by gen_c3_hierarchy.py (the catalog pages of the one hierarchy); never edit them."
    optext = json.dumps(ops, indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        bad = [n for n, t in ((OUT, text), (OPS, optext)) if open(n, encoding="utf-8").read() != t]
        if bad:
            sys.exit("stale generated file(s): %s - run data/gen_c3_hierarchy.py" % ", ".join(os.path.basename(b) for b in bad))
        return
    open(OUT, "w", encoding="utf-8").write(text)
    open(OPS, "w", encoding="utf-8").write(optext)


if __name__ == "__main__":
    main()
