package com.diegonmarcos.superapp.shellrish

import com.diegonmarcos.superapp.shellclient.ShellClient
import android.content.Context
import java.io.File

/**
 * #1512 `rish` for the terminals (Cloud Terminal, Cloud Nix terminal), over the SuperApp's shell broker instead of a Shizuku binder or an
 * ADB channel of their own. [export] starts the in-process [RishRelay] (once) and writes, into [loginDir]/rish, the `rish` launcher and a
 * 0600 `rish.env` with the relay's loopback URL and this process's random token; the proot login binds both (rootfs/enter.sh,
 * bake_default_packages.py). Called from the terminal app's onCreate and after a bootstrap; safe to call again (the files are rewritten
 * only when they change).
 */
object ShellRish {
    @Volatile private var relay: RishRelay? = null
    @Volatile private var port = 0
    private var token = ""

    @JvmStatic
    @Synchronized fun export(ctx: Context, loginDir: File) {
        val app = ctx.applicationContext
        if (relay == null) {
            token = RishRelay.newToken()
            val client = ShellClient.over(app)
            relay = RishRelay(token) { cmd, t -> client.exec(cmd, t) }.also { port = it.start() }
        }
        runCatching {
            val dir = File(loginDir, "rish").apply { mkdirs() }
            writeIfChanged(File(dir, "rish"), launcher(), "0755")
            writeIfChanged(File(dir, "rish.env"), env(port, token), "0600")
        }
    }

    /** The environment `rish` sources: the relay's URL and the bearer token (never in source: random per process). */
    internal fun env(port: Int, token: String): String =
        "RISH_BRIDGE_URL=http://127.0.0.1:$port/exec\nRISH_BRIDGE_TOKEN=$token\n"

    /** POSIX sh (busybox-safe), no jq: urlencodes with od, prints the body, exits with the broker's exit code. */
    internal fun launcher(): String = LAUNCHER

    private fun writeIfChanged(f: File, body: String, mode: String) {
        if (f.isFile && f.readText() == body) return
        val tmp = File(f.parentFile, f.name + ".new")
        tmp.writeText(body)
        runCatching { android.system.Os.chmod(tmp.absolutePath, mode.toInt(8)) }
        android.system.Os.rename(tmp.absolutePath, f.absolutePath)
    }

    // The sentinel U+00A7 would stand in for '$' in a Kotlin template; a raw string with ${'$'} is clumsier, so the launcher lives as plain text with the
    // shell variables escaped through a replace.
    private val LAUNCHER = """#!/bin/sh
# rish: the Cloud terminal's privileged-shell bridge (Shizuku-style). GENERATED by ShellRish (libs:shell-client); do not edit.
# Runs its argv as a shell command at adb-shell (uid 2000) privilege through the SuperApp's shell broker: one loopback request to the
# terminal app's relay, which the broker answers under the terminal's own allowlist (default deny). Exit code = the command's.
set -u
: "@{RISH_ENV:=/usr/local/etc/rish.env}"
[ -r "@RISH_ENV" ] || { echo "rish: @RISH_ENV missing: open the terminal app so it writes it" >&2; exit 1; }
. "@RISH_ENV"
if [ "@#" -eq 0 ]; then echo "usage: rish <command...>   (runs through the ADB shell of Cloud C3 Webserver; only allowlisted commands)" >&2; exit 2; fi
enc=@(printf '%s' "@*" | od -An -v -tx1 | tr -d ' \n' | sed 's/../%&/g')
h="@{TMPDIR:-/tmp}/rish.@@"
trap 'rm -f "@h.h" "@h.b"' EXIT
curl -sS -D "@h.h" -o "@h.b" -H "Authorization: Bearer @RISH_BRIDGE_TOKEN" "@RISH_BRIDGE_URL?t=@{RISH_TIMEOUT_MS:-15000}&cmd=@enc" \
    || { echo "rish: the terminal app's bridge is not running: reopen the terminal app" >&2; exit 1; }
cat "@h.b"
code=@(sed -n 's/^[Xx]-[Ee]xit-[Cc]ode: *//p' "@h.h" | tr -d '\r' | head -n 1)
exit "@{code:-1}"
""".replace('@', '$')
}
