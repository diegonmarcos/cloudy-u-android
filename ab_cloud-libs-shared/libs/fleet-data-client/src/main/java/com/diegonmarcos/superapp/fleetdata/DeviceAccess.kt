package com.diegonmarcos.superapp.fleetdata

import android.content.Context
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.intOrNull

/**
 * THE device access model (#1718): what this phone exposes and who may reach it, as ONE parsed document. Cloud Store > Access and
 * Cloud C3 Webserver > API both draw this class, so the two pages cannot disagree: there is one list, not two.
 *
 * DATA, never baked here: the document is the runtime dataset `shared/device-access` (data/fleet/device-access.json, GENERATED by
 * 1_cicd/src/scripts/cloud-android-device-access.py from the declarations: the fleet rows, the IPC registry, the gateway and port
 * table, the webserver's API -> IPC map, the MCP catalogue, each app's api_endpoints, the shared-uid groups, the ADB owner). The
 * Store reads it through [load] (its own fleet data provider); the webserver's Rust core compiles the same file in and hands the
 * text to [parse].
 *
 * Every read is defensive: a missing key is an empty list or "", a malformed document is [EMPTY] with the reason in [problem],
 * never a throw.
 */
object DeviceAccess {
    const val DATASET = "device-access"
    /** The schemaVersion this parser reads; a newer document is refused with a reason. */
    const val SUPPORTED = 1

    /** A gateway: the ONE door of its kind. `debug` = the on-phone API gateway, `mesh` = the one mesh gateway (#1580). */
    data class Gateway(
        val id: String, val pkg: String, val app: String, val bind: String, val port: Int?, val route: String, val roster: String,
        val listener: String, val auth: String, val cidrs: List<String>, val ipcRoute: String, val logsRoute: String,
        val endpointsRoute: String, val aliases: Map<String, String>, val what: String,
    ) {
        /** `127.0.0.1:38080` or `mesh address:8004`: where the door listens, in words when the address is resolved at run time. */
        val address: String get() = (bind.ifEmpty { listener.ifEmpty { "?" } }) + (port?.let { ":$it" } ?: "")
    }

    data class Surface(val id: String, val listener: String, val auth: String)
    data class Peer(val id: String, val scopes: List<String>, val what: String) {
        val full: Boolean get() = "*" in scopes
    }

    /** A route an MCP tool lands on, on this device. */
    data class ToolRoute(val path: String, val surface: String, val method: String, val acl: String)
    /** One MCP tool that acts on this device; [door] is the gateway id it comes in through. */
    data class Tool(val tool: String, val legacy: String?, val tree: String, val door: String, val routes: List<ToolRoute>)
    data class Mcp(val server: String, val endpoint: String, val auth: String, val aliases: List<String>, val node: String, val tools: List<Tool>)

    data class Kind(val id: String, val label: String, val what: String)
    /** A declared endpoint ({method, path, what}); [url] carries the shared default's base when it is inherited. */
    data class Endpoint(val method: String, val path: String, val what: String, val url: String = path)
    data class SharedDebug(val lib: String, val service: String, val base: String, val endpoints: List<Endpoint>)

    /** One route of an app's own listener (the webserver's ROUTES, mesh and diag surfaces). */
    data class Route(val path: String, val surface: String, val method: String, val ipc: List<String>, val via: String, val mcpTools: List<String>)

    /** One IPC route of an app behind the mesh gateway: `<ipc_route>/<app>/<route>`. */
    data class IpcRoute(
        val route: String, val path: String, val method: String, val kind: String, val authority: String, val methods: List<String>,
        val acl: String, val status: String, val mcpTool: String?, val legacyRoute: String?, val appClass: String, val what: String,
    )

    /** A per-app IPC endpoint every member carries (build.json::api.ipc), `{package}` filled. */
    data class IpcEndpoint(val id: String, val kind: String, val authority: String, val methods: String, val guard: String, val what: String)

    data class App(
        val id: String, val pkg: String, val label: String, val kind: String, val door: Boolean, val port: Int?,
        val engines: List<String>, val ops: List<String>, val routes: List<Route>, val declared: Map<String, List<Endpoint>>,
        val ipc: List<IpcRoute>,
    ) {
        /** Every API route this app really exposes: its ops, its own listener's routes and the endpoints it declares. Never 0 for an app that declares one. */
        val apiCount: Int get() = ops.size + routes.size + declared.values.sumOf { it.size }
        val ipcCount: Int get() = ipc.size
    }

    data class Group(val id: String, val label: String, val sharedUserId: String?, val members: List<String>)
    data class AdbOwner(val app: String, val pkg: String, val dir: String)

    data class Doc(
        val permission: String, val permissionLevel: String, val doorAuthority: String, val doorMethod: String, val doorProbe: String,
        val gateways: List<Gateway>, val surfaces: List<Surface>, val scopes: Map<String, String>, val peers: List<Peer>, val mcp: Mcp,
        val kinds: List<Kind>, val sharedDebug: SharedDebug, val ipcTemplates: List<IpcEndpoint>, val engineAction: String,
        val apps: List<App>, val groups: List<Group>, val adbOwner: AdbOwner,
        /** Why the document is empty or partial; null when it parsed. */
        val problem: String? = null,
    ) {
        fun gateway(id: String): Gateway? = gateways.firstOrNull { it.id == id }
        fun app(idOrPkg: String): App? = apps.firstOrNull { it.id == idOrPkg || it.pkg == idOrPkg }

        /** The apps of [kind] ("app" / "lib"), A-Z by label; null = every member. */
        fun members(kind: String? = "app"): List<App> = apps.filter { kind == null || it.kind == kind }.sortedBy { it.label.lowercase() }

        val apiTotal: Int get() = apps.sumOf { it.apiCount }
        val ipcTotal: Int get() = apps.sumOf { it.ipcCount }

        /** Apps that expose the fleet door (so declare an API) yet count zero routes: must be empty; the page says so when it is not. */
        fun zeroApis(): List<App> = apps.filter { it.door && it.apiCount == 0 }

        /** [app]'s declared endpoints of [kind]; the debug kind inherits the shared default when the app declares none. */
        fun declared(app: App, kind: String): List<Endpoint> = app.declared[kind].orEmpty().ifEmpty { if (inherits(app, kind)) sharedDebug.endpoints else emptyList() }
        fun inherits(app: App, kind: String): Boolean = kind == "debug" && app.declared[kind].isNullOrEmpty() && sharedDebug.endpoints.isNotEmpty()

        /** The per-app IPC endpoints of [app]: every template with its package, plus the engine action when it binds engines. */
        fun ipcEndpoints(app: App): List<IpcEndpoint> =
            ipcTemplates.map { it.copy(authority = it.authority.replace(PKG, app.pkg)) } +
                if (app.engines.isEmpty() || engineAction.isEmpty()) emptyList()
                else listOf(IpcEndpoint("engine", "service", engineAction.replace(PKG, app.pkg), "binds " + app.engines.joinToString(", "), "", "the engines this app binds"))

        /** The gateway address of one op of [app]: the debug gateway's route with the app and the op filled. */
        fun opUrl(app: App, op: String): String {
            val g = gateway("debug") ?: return op
            return "http://" + g.address + g.route.replace("<id|pkg>", app.id).replace("<op>", op)
        }

        /** Groups whose members share one Linux uid: they read each other's files with no IPC at all. */
        fun sharedUid(): List<Group> = groups.filter { it.sharedUserId != null && it.members.size > 1 }

        /** The tools that come in through gateway [door]. */
        fun tools(door: String): List<Tool> = mcp.tools.filter { it.door == door }

        fun summary(): String = "${members().size} apps · ${members("lib").size} libs · ${mcp.tools.size} device MCP tools · $apiTotal API routes · $ipcTotal IPC routes"
    }

    const val PKG = "{package}"

    val EMPTY = Doc("", "", "", "", "", emptyList(), emptyList(), emptyMap(), emptyList(), Mcp("", "", "", emptyList(), "", emptyList()),
        emptyList(), SharedDebug("", "", "", emptyList()), emptyList(), "", emptyList(), emptyList(), AdbOwner("", "", ""))

    /** The dataset as the Store's fleet data provider serves it; [EMPTY] with a reason while nothing is served. */
    fun load(ctx: Context): Doc =
        runCatching { FleetData.get(ctx, DATASET) { parse(it) } }.getOrNull()
            ?: EMPTY.copy(problem = "The device access dataset is not served yet (Cloud Store syncs it from the fleet data manifest).")

    /** Parses the dataset. Never throws. */
    fun parse(text: String): Doc {
        val root = (try { Json.parseToJsonElement(text) as? JsonObject } catch (e: Exception) { null })
            ?: return EMPTY.copy(problem = "The device access dataset is not a JSON object.")
        val v = root.prim("schemaVersion")?.intOrNull
        if (v == null || v < 1 || v > SUPPORTED) return EMPTY.copy(problem = "The device access dataset has schemaVersion ${v ?: "none"}; this app reads $SUPPORTED.")
        return try { doc(root) } catch (e: Exception) { EMPTY.copy(problem = "The device access dataset could not be read: ${e.javaClass.simpleName}.") }
    }

    private fun doc(o: JsonObject): Doc {
        val gws = o.obj("gateways")
        val mcp = o.obj("mcp")
        val sd = o.obj("shared_debug")
        val base = sd.str("base").trimEnd('/')
        val owner = o.obj("privileged").obj("adb_owner")
        return Doc(
            permission = o.obj("permission").str("name"), permissionLevel = o.obj("permission").str("level"),
            doorAuthority = o.obj("door").str("authority"), doorMethod = o.obj("door").str("method"), doorProbe = o.obj("door").str("probe"),
            gateways = gws.keys.map { id -> gateway(id, gws.obj(id)) },
            surfaces = o.obj("surfaces").let { s -> s.keys.map { Surface(it, s.obj(it).str("listener"), s.obj(it).str("auth")) } },
            scopes = o.obj("acl_scopes").let { s -> s.keys.associateWith { s.str(it) } },
            peers = o.arr("peers").map { Peer(it.str("id"), it.strs("scopes"), it.str("what")) },
            mcp = Mcp(mcp.str("server"), mcp.str("endpoint"), mcp.str("auth"), mcp.strs("aliases"), mcp.str("node"),
                mcp.arr("tools").map { t -> Tool(t.str("tool"), t.strOrNull("legacy"), t.str("tree"), t.str("door"),
                    t.arr("routes").map { ToolRoute(it.str("path"), it.str("surface"), it.str("method").ifEmpty { "GET" }, it.str("acl")) }) }),
            kinds = o.arr("kinds").map { Kind(it.str("id"), it.str("label").ifEmpty { it.str("id") }, it.str("what")) },
            sharedDebug = SharedDebug(sd.str("lib"), sd.str("service"), base, sd.arr("endpoints").map { endpoint(it, base) }),
            ipcTemplates = o.arr("ipc_templates").map { IpcEndpoint(it.str("id"), it.str("kind"), it.str("authority"), it.str("methods"), it.str("guard"), it.str("what")) },
            engineAction = o.str("engine_action"),
            apps = o.arr("apps").filter { it.str("id").isNotEmpty() && it.str("pkg").isNotEmpty() }.map { app(it) },
            groups = o.obj("identity").arr("groups").map { Group(it.str("id"), it.str("label").ifEmpty { it.str("id") }, it.strOrNull("uid"), it.strs("members")) },
            adbOwner = AdbOwner(owner.str("app"), owner.str("pkg"), owner.str("dir")),
        )
    }

    private fun gateway(id: String, g: JsonObject) = Gateway(
        id, g.str("pkg"), g.str("app"), g.str("bind"), g.prim("port")?.intOrNull, g.str("route"), g.str("roster"), g.str("listener"), g.str("auth"),
        g.strs("cidrs"), g.str("ipc_route"), g.str("logs_route"), g.str("endpoints_route"), g.obj("aliases").let { a -> a.keys.associateWith { a.str(it) } }, g.str("what"))

    private fun endpoint(e: JsonObject, base: String) = Endpoint(e.str("method"), e.str("path"), e.str("what"), base + e.str("path"))

    private fun app(a: JsonObject): App {
        val declared = a.obj("declared")
        return App(
            a.str("id"), a.str("pkg"), a.str("label").ifEmpty { a.str("id") }, a.str("kind").ifEmpty { "app" }, a.prim("door")?.booleanOrNull == true,
            a.prim("port")?.intOrNull, a.strs("engines"), a.strs("ops"),
            a.arr("routes").map { Route(it.str("path"), it.str("surface"), it.str("method").ifEmpty { "GET" }, it.strs("ipc"), it.str("via"), it.strs("mcp_tools")) },
            declared.keys.associateWith { k -> declared.arr(k).map { endpoint(it, "") } },
            a.arr("ipc").map { IpcRoute(it.str("route"), it.str("path"), it.str("method").ifEmpty { "GET" }, it.str("kind"), it.str("authority"), it.strs("methods"),
                it.str("acl"), it.str("status"), it.strOrNull("mcp_tool"), it.strOrNull("legacy_route"), it.str("class"), it.str("what")) },
        )
    }

    // ── what both pages print (so a row reads the same in the Store and in the webserver) ────────────────────────────

    fun line(r: IpcRoute): String = "${r.method} ${r.path}  ·  ${r.kind} ${r.authority}" +
        (if (r.methods.isEmpty()) "" else "  ·  " + r.methods.joinToString(" | ")) + "  ·  acl ${r.acl.ifEmpty { "none" }}  ·  ${r.status.ifEmpty { "?" }}" +
        (r.mcpTool?.let { "  ·  MCP $it" } ?: "") + (r.legacyRoute?.let { "  ·  retires $it" } ?: "")

    fun line(r: Route): String = "${r.method} ${r.path}  ·  ${r.surface}" + (if (r.ipc.isEmpty()) "" else "  ·  ipc " + r.ipc.joinToString(", ")) +
        (if (r.mcpTools.isEmpty()) "" else "  ·  MCP " + r.mcpTools.joinToString(", "))

    fun line(t: Tool): String = t.tool + (t.legacy?.let { "  (was $it)" } ?: "") +
        (if (t.routes.isEmpty()) "" else "  →  " + t.routes.joinToString("  |  ") { "${it.method} ${it.path}" + if (it.acl.isEmpty()) "" else " [${it.acl}]" })

    /** The whole model as text, for Copy and for the parity tests: every field of every row appears once. */
    fun report(d: Doc): String = buildString {
        appendLine("# Device access"); appendLine(d.summary())
        d.problem?.let { appendLine("PROBLEM: $it") }
        appendLine("## Gateways")
        for (g in d.gateways) appendLine("- ${g.id}: ${g.app} (${g.pkg}) ${g.address} ${g.route}${g.ipcRoute.ifEmpty { "" }} · ${g.auth} · ${g.what}")
        appendLine("## MCP (device) · ${d.mcp.server} ${d.mcp.endpoint} · ${d.mcp.auth} · aliases ${d.mcp.aliases.joinToString(", ")}")
        for (t in d.mcp.tools) appendLine("- [${t.door}] ${line(t)}")
        appendLine("## Scopes"); for ((k, v) in d.scopes) appendLine("- $k: $v")
        appendLine("## Peers"); for (p in d.peers) appendLine("- ${p.id}: ${p.scopes.joinToString(", ")} · ${p.what}")
        for (a in d.apps) {
            appendLine("## ${a.label} (${a.id}, ${a.pkg}) · ${a.kind} · port ${a.port ?: "none"} · ${a.apiCount} API · ${a.ipcCount} IPC")
            for (op in a.ops) appendLine("- op $op")
            for (r in a.routes) appendLine("- route ${line(r)}")
            for (k in d.kinds) for (e in d.declared(a, k.id)) appendLine("- ${k.label}${if (d.inherits(a, k.id)) " (shared ${d.sharedDebug.lib})" else ""}: ${e.method} ${e.url}")
            for (r in a.ipc) appendLine("- ipc ${line(r)}")
            for (e in d.ipcEndpoints(a)) appendLine("- endpoint ${e.kind} ${e.authority} ${e.methods}")
        }
        appendLine("## Identity · ${d.permission} (${d.permissionLevel})")
        for (g in d.groups) appendLine("- ${g.label}: ${g.sharedUserId ?: "own uid each"} · ${g.members.joinToString(", ")}")
        appendLine("## ADB owner · ${d.adbOwner.app} (${d.adbOwner.pkg})")
    }

    // ── JSON reading that cannot throw ──────────────────────────────────────────────────────────────────────────────
    private fun JsonObject.prim(k: String): JsonPrimitive? = (this[k] as? JsonPrimitive)?.takeIf { it !is JsonNull }
    private fun JsonObject.str(k: String): String = prim(k)?.content.orEmpty()
    private fun JsonObject.strOrNull(k: String): String? = prim(k)?.content?.takeIf { it.isNotEmpty() }
    private fun JsonObject.obj(k: String): JsonObject = (this[k] as? JsonObject)?.let { o -> JsonObject(o.filterKeys { !it.startsWith("_") }) } ?: JsonObject(emptyMap())
    private fun JsonObject.arr(k: String): List<JsonObject> = (this[k] as? JsonArray)?.mapNotNull { it as? JsonObject }.orEmpty()
    private fun JsonObject.strs(k: String): List<String> = (this[k] as? JsonArray)?.mapNotNull { e: JsonElement -> (e as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content }.orEmpty()
}
