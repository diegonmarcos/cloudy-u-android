#!/usr/bin/env python3
"""#1423 generator of the World clock's declared data (run by hand, output committed; no build runs it).

  python3 -I worldclock.py CITIES500.txt COUNTRYINFO.txt NE_110M_LAND.geojson OUT_ASSETS_DIR

CITIES500.txt / countryInfo.txt: GeoNames dumps (download.geonames.org/export/dump, CC BY 4.0).
ne_110m_land.geojson: Natural Earth 1:110m land (public domain, github.com/nvkelso/natural-earth-vector).
Writes worldmap/cities.json (every country's capital; BIG countries also their most populous cities;
every IANA region zone of this Python's zoneinfo) and worldmap/land.json (coordinates rounded to 0.1 deg).
"""
import json, sys, zoneinfo

BIG = ["US", "CA", "BR", "RU", "CN", "IN", "AU", "MX", "ID", "AR", "KZ", "DZ", "CD", "SA"]
EXTRA = 4  # most populous non-capital cities added for each BIG country
SKIP = {"Brooklyn", "Queens", "Manhattan", "The Bronx"}  # boroughs GeoNames lists beside New York City

def main(cities, info, land, out):
    countries, rows = [], []
    for ln in open(info, encoding="utf-8"):
        if ln.startswith("#") or not ln.strip(): continue
        f = ln.rstrip("\n").split("\t")
        countries.append({"code": f[0], "name": f[4], "capital": f[5]})
    by_cc = {}
    for ln in open(cities, encoding="utf-8"):
        f = ln.rstrip("\n").split("\t")
        if f[6] != "P": continue
        by_cc.setdefault(f[8], []).append(dict(name=f[1], fcode=f[7], lat=float(f[4]), lon=float(f[5]),
                                               pop=int(f[14] or 0), zone=f[17]))
    out_cities, seen = [], set()
    def add(c, cc, cap):
        k = (cc, c["name"])
        if k in seen or not c["zone"]: return
        seen.add(k)
        out_cities.append({"name": c["name"], "country": cc, "zone": c["zone"],
                           "lat": round(c["lat"], 4), "lon": round(c["lon"], 4), "capital": cap})
    no_capital = []
    for co in countries:
        cc, pl = co["code"], by_cc.get(co["code"], [])
        caps = [c for c in pl if c["fcode"] == "PPLC"]
        if not caps and co["capital"]:  # e.g. PS: GeoNames lists East Jerusalem as PPLX
            caps = sorted([c for c in pl if c["name"] in (co["capital"], "East " + co["capital"])], key=lambda c: -c["pop"])[:1]
        if not caps:
            no_capital.append(cc); continue
        for c in caps: add(c, cc, True)
        if cc in BIG:
            for c in sorted([c for c in pl if c["fcode"] not in ("PPLC", "PPLX") and c["name"] not in SKIP], key=lambda c: -c["pop"])[:EXTRA]: add(c, cc, False)
    zones = sorted(z for z in zoneinfo.available_timezones()
                   if "/" in z and not z.startswith(("Etc/", "SystemV/", "posix/", "right/")))
    doc = {"_doc": "#1423 World clock cities and zones, generated by ac_cloud-calc/data/gen/worldclock.py from GeoNames "
                   "(CC BY 4.0, geonames.org): every country's capital (capital=true) and, for big_countries, their most "
                   "populous cities; zones = every IANA region zone. Tests: tools/WorldCitiesTest.kt.",
           "big_countries": BIG, "min_big_cities": 3, "no_capital": no_capital,
           "countries": [{"code": c["code"], "name": c["name"]} for c in countries if c["code"] not in no_capital],
           "cities": out_cities, "zones": zones}
    json.dump(doc, open(f"{out}/worldmap/cities.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0, separators=(",", ":"))
    polys = []
    for ft in json.load(open(land))["features"]:
        g = ft["geometry"]
        for poly in ([g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]):
            ring, flat = poly[0], []
            for lon, lat in ring:
                p = [round(lon, 1), round(lat, 1)]
                if flat[-2:] != p: flat += p
            if len(flat) >= 6: polys.append(flat)
    json.dump({"_doc": "#1423 Natural Earth 1:110m land (public domain), outer rings as flat [lon,lat,...] arrays, 0.1 deg; "
                       "generated by ac_cloud-calc/data/gen/worldclock.py", "polygons": polys},
              open(f"{out}/worldmap/land.json", "w"), separators=(",", ":"))
    print(len(out_cities), "cities,", len(zones), "zones,", len(polys), "polygons; no capital:", no_capital)

if __name__ == "__main__": main(*sys.argv[1:5])
