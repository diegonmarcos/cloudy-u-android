#!/usr/bin/env python3
"""#1887 generator of the offline gazetteer Cloud Nav names imported places with (run by hand, output committed; no build runs it).

  python3 -I gen-gazetteer.py CITIES15000.txt COUNTRYINFO.txt OUT.tsv

CITIES15000.txt / countryInfo.txt: GeoNames dumps (download.geonames.org/export/dump, CC BY 4.0, geonames.org).
OUT.tsv (app/src/main/assets/geo/gazetteer.tsv): one populated place per line, `name<TAB>country<TAB>lat<TAB>lon<TAB>zone`,
country = the English country name (what Continents.of reads), zone = the IANA time zone (the Day page's sleep-city daylight).
A location import without addresses (a Timeline KML) gets its City and Country from the nearest entry (Gazetteer.kt).
"""
import sys

def main(cities, info, out):
    names = {}
    for ln in open(info, encoding="utf-8"):
        if ln.startswith("#") or not ln.strip(): continue
        f = ln.rstrip("\n").split("\t")
        names[f[0]] = f[4]
    rows = []
    for ln in open(cities, encoding="utf-8"):
        f = ln.rstrip("\n").split("\t")
        if len(f) < 18 or f[6] != "P" or not f[17]: continue
        country = names.get(f[8])
        if not country: continue
        name = f[1].replace("\t", " ").strip()
        rows.append((name, country, round(float(f[4]), 4), round(float(f[5]), 4), f[17]))
    rows.sort(key=lambda r: (r[1], r[0], r[2], r[3]))
    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write("# GeoNames cities15000 (CC BY 4.0, geonames.org), generated by ac_cloud-nav/test/gen-gazetteer.py: name, country, lat, lon, zone\n")
        for r in rows: o.write("%s\t%s\t%s\t%s\t%s\n" % r)
    print(len(rows), "places")

if __name__ == "__main__":
    main(*sys.argv[1:4])
