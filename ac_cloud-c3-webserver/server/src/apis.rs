//! The API tab's sub-pages (MCP, Mesh Endpoints, Apps Endpoints, Apps IPC) as data. #1718: the tab shows ONLY this device; the fleet
//! services' public and mesh URLs (`public_page`, the fleet group of `mesh_page`) are no page of it any more (they are Cloud C3's) and
//! stay only behind the mesh listener's `/endpoints` JSON, which cloudy-c3-mcp reads off the device.
//!
//! Nothing here names an app, a service or a port: every row is read from declarations that already exist (build.json::api.sources,
//! resolved by build.rs into `api-data.json`: the fleet services, the per-app debug ports, the fleet manifest) and from this
//! app's own build.json (`api.ipc` templates, `mesh`). A page is `{title, note, groups:[{title, rows:[{head, badges, lines,
//! links:[{label, href}], actions}]}]}`, the one shape the shell draws for every sub-page (dense rows).

use crate::meshlogs::Mesh;
use crate::serving;
use serde_json::{json, Value};
use std::sync::OnceLock;

pub const API_DATA: &str = include_str!(concat!(env!("OUT_DIR"), "/api-data.json"));

/// This app's resolved build.json.
pub fn build() -> &'static Value {
    static B: OnceLock<Value> = OnceLock::new();
    B.get_or_init(|| serde_json::from_str(serving::BUILD_JSON).expect("build.json parses (serving::parse checks it)"))
}

pub fn data() -> &'static Value {
    static D: OnceLock<Value> = OnceLock::new();
    D.get_or_init(|| serde_json::from_str(API_DATA).expect("api-data.json parses"))
}

#[derive(Clone, Debug, PartialEq)]
pub struct App {
    pub id: String,
    pub name: String,
    pub package: String,
    pub engines: Vec<String>,
}

/// The fleet manifest's applications (kind `app`): the ONLY list of apps anywhere in this crate.
pub fn apps_from(d: &Value) -> Vec<App> {
    d["fleet"]
        .as_array()
        .map(|a| a.as_slice())
        .unwrap_or(&[])
        .iter()
        .filter(|a| a["kind"] == "app")
        .filter_map(|a| {
            Some(App {
                id: a["id"].as_str()?.to_string(),
                name: a["display_name"].as_str().or(a["label"].as_str()).unwrap_or_else(|| a["id"].as_str().unwrap_or("")).to_string(),
                package: a["package"].as_str()?.to_string(),
                engines: a["engines"].as_array().map(|e| e.iter().filter_map(|x| x["binding"].as_str().map(str::to_string)).collect()).unwrap_or_default(),
            })
        })
        .collect()
}

pub fn apps() -> &'static Vec<App> {
    static A: OnceLock<Vec<App>> = OnceLock::new();
    A.get_or_init(|| apps_from(data()))
}

fn fill(tpl: &str, pkg: &str) -> String {
    tpl.replace("{package}", pkg)
}

fn s(v: &Value) -> String {
    v.as_str().unwrap_or("").to_string()
}

fn row(head: &str, badges: Vec<String>, lines: Vec<String>, links: Vec<(String, String)>) -> Value {
    json!({"head": head, "badges": badges, "lines": lines, "links": links.into_iter().map(|(l, h)| json!({"label": l, "href": h})).collect::<Vec<_>>()})
}

pub fn page(title: &str, note: &str, groups: Vec<Value>) -> Value {
    json!({"title": title, "note": note, "groups": groups})
}

pub fn group(title: &str, rows: Vec<Value>) -> Value {
    json!({"title": title, "rows": rows})
}

/// The public URL of a fleet service (scheme, domain, path), when it has one.
pub fn public_url(svc: &Value) -> Option<String> {
    let d = svc["public_domain"].as_str().filter(|d| !d.is_empty())?;
    Some(format!("{}://{}{}", svc["public_scheme"].as_str().unwrap_or("https"), d, svc["public_path"].as_str().unwrap_or("")))
}

/// The mesh URL of a fleet service, when it has one.
pub fn mesh_url(svc: &Value) -> Option<String> {
    let d = svc["mesh_dns"].as_str().filter(|d| !d.is_empty())?;
    let port = svc["mesh_port"].as_u64().map(|p| format!(":{}", p)).unwrap_or_default();
    Some(format!("{}://{}{}{}", svc["mesh_scheme"].as_str().unwrap_or("http"), d, port, svc["mesh_path"].as_str().unwrap_or("")))
}

/// The MCP tool catalogue (build.json::api.sources.mcp_catalogue, generated by data/gen_mcp_catalogue.py): one group per MCP server (its
/// aliases, endpoint, auth, the API it fronts), one row per tool with the API route it maps to; a server whose tools the generator cannot
/// enumerate is one row with its tool count.
pub fn mcp_page(d: &Value) -> Value {
    let servers = d["mcp_catalogue"].as_array().map(|a| a.as_slice()).unwrap_or(&[]);
    let groups: Vec<Value> = servers
        .iter()
        .map(|sv| {
            let name = s(&sv["name"]);
            let auth = s(&sv["auth"]);
            let tools = sv["tools"].as_array().map(|a| a.as_slice()).unwrap_or(&[]);
            let api = sv["api"].as_str().filter(|a| !a.is_empty()).map(|a| format!("API {}", a)).unwrap_or_else(|| "no API of its own".to_string());
            let rows: Vec<Value> = if tools.is_empty() {
                vec![row(&format!("{} tools", sv["tools_count"].as_u64().unwrap_or(0)), vec![name.clone(), auth.clone()], vec![format!("listed by the server itself (tools/list); {}", api)], vec![])]
            } else {
                tools
                    .iter()
                    .map(|t| {
                        let mut lines = vec![format!("API route {}", s(&t["route"]))];
                        lines.push(format!("tree {}", s(&t["tree"])));
                        if let Some(l) = t["legacy"].as_str() {
                            lines.push(format!("old name {}", l));
                        }
                        row(&s(&t["tool"]), vec![name.clone(), auth.clone()], lines, vec![])
                    })
                    .collect()
            };
            let aliases = sv["aliases"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).collect::<Vec<_>>().join(", ")).unwrap_or_default();
            let head = format!("{} · {} · {} tools{}", name, auth, sv["tools_count"].as_u64().unwrap_or(0), if aliases.is_empty() { String::new() } else { format!(" · aliases {}", aliases) });
            let mut g = group(&head, rows);
            g["endpoint"] = sv["endpoint"].clone();
            g
        })
        .collect();
    page("MCP", "The MCP tool catalogue of all our APIs and MCP servers, GENERATED from the declarations (the containers' build.json files, mcp-policy.json, api-renames.json, the cloudy-c3-api route hierarchy): tool, the API route it maps to, the server and the auth the edge enforces.", groups)
}

pub fn public_page(d: &Value) -> Value {
    let rows: Vec<Value> = d["services"]
        .as_array()
        .map(|a| a.as_slice())
        .unwrap_or(&[])
        .iter()
        .filter_map(|v| {
            let url = public_url(v)?;
            let mut lines = vec![];
            if let Some(h) = v["health"].as_str() {
                lines.push(format!("health {}", h));
            }
            Some(row(&s(&v["id"]), vec![s(&v["kind"]), s(&v["policy"])].into_iter().filter(|b| !b.is_empty()).collect(), lines, vec![(url.clone(), url)]))
        })
        .collect();
    page("Public Endpoints", "The public URLs of the fleet services, from the fleet endpoint declaration (Cloud Account). Reach them with the fleet bearer where the policy says so.", vec![group(&format!("{} public URLs", rows.len()), rows)])
}

/// #1725 The catalogue of THIS DEVICE: of every MCP server, only the tools that act on this phone (the device access model's
/// `mcp.tools`, i.e. the catalogue tools of its device node), and only the servers that carry one. The remote servers and their
/// c3-api routes are no part of this app's pages any more: they are Cloud C3 > Infra > APIs > C3 MCP.
pub fn device_catalogue(d: &Value) -> Value {
    let device: Vec<&str> = d["device_access"]["mcp"]["tools"].as_array().map(|a| a.iter().filter_map(|t| t["tool"].as_str()).collect()).unwrap_or_default();
    let servers: Vec<Value> = d["mcp_catalogue"]
        .as_array()
        .map(|a| a.as_slice())
        .unwrap_or(&[])
        .iter()
        .filter_map(|sv| {
            let tools: Vec<Value> = sv["tools"].as_array().map(|a| a.as_slice()).unwrap_or(&[]).iter().filter(|t| t["tool"].as_str().map(|n| device.contains(&n)).unwrap_or(false)).cloned().collect();
            if tools.is_empty() {
                return None;
            }
            let mut one = sv.clone();
            one["tools_count"] = json!(tools.len());
            one["tools"] = Value::Array(tools);
            Some(one)
        })
        .collect();
    Value::Array(servers)
}

/// The MCP page of the app's own API tab (#1725): the device's own MCP tools only.
pub fn device_mcp_page(d: &Value) -> Value {
    let mut p = mcp_page(&json!({"mcp_catalogue": device_catalogue(d)}));
    p["note"] = json!("The MCP tools that act on this phone, from the generated catalogue: tool, the server that carries it and the auth the edge enforces. The other MCP servers and the c3-api routes they map to are Cloud C3 > Infra > APIs > C3 MCP.");
    p
}

/// The title prefix of the one group of [mesh_page] that is not this device's.
pub const FLEET_MESH_GROUP: &str = "Fleet services on the mesh";

/// The Mesh Endpoints page of the app's own API tab (#1718): this phone's mesh listener and the apps behind it, nothing of the fleet's
/// other machines.
pub fn device_mesh_page(m: &Mesh, apps: &[App]) -> Value {
    let mut p = mesh_page(&Value::Null, m, apps);
    if let Some(g) = p["groups"].as_array_mut() {
        g.retain(|x| !x["title"].as_str().unwrap_or("").starts_with(FLEET_MESH_GROUP));
    }
    p
}

pub fn mesh_page(d: &Value, m: &Mesh, apps: &[App]) -> Value {
    let base = format!("http://{}:{}", m.bind, m.port);
    let mut head = vec![row(
        &format!("{}{}", base, m.route),
        vec!["GET".into(), "Bearer".into(), "mesh only".into()],
        vec![format!("the apps that export logs; peers from {} only; every path needs the fleet bearer", m.cidr_text())],
        vec![],
    )];
    head.push(row(&format!("{}{}/public | mesh", base, m.endpoints_route), vec!["GET".into(), "Bearer".into()], vec!["these Public and Mesh Endpoints pages as JSON (for cloudy-c3-mcp)".to_string()], vec![]));
    head.push(row(&format!("{}{}/<app>?n=&errors=&crashes=&method=", base, m.route), vec!["GET".into(), "Bearer".into()], vec![format!("calls <package>.{} of that app: {}", m.suffix, m.methods.join(" | "))], vec![]));
    let logs: Vec<Value> = apps.iter().map(|a| row(&a.name, vec![a.id.clone()], vec![format!("{}.{}", a.package, m.suffix)], vec![(format!("{}{}/{}", base, m.route, a.id), format!("{}{}/{}", base, m.route, a.id))])).collect();
    let svc: Vec<Value> = d["services"]
        .as_array()
        .map(|a| a.as_slice())
        .unwrap_or(&[])
        .iter()
        .filter_map(|v| {
            let url = mesh_url(v)?;
            Some(row(&s(&v["id"]), vec![s(&v["policy"])].into_iter().filter(|b| !b.is_empty()).collect(), vec![], vec![(url.clone(), url)]))
        })
        .collect();
    page(
        "Mesh Endpoints",
        "This phone's mesh listener routes each app's log export (libs:log-export) onto the mesh. It is bound to the mesh address only, never public.",
        vec![group("Cloud-Webserver on the mesh", head), group(&format!("Apps logs · {}", logs.len()), logs), group(&format!("{} · {}", FLEET_MESH_GROUP, svc.len()), svc)],
    )
}

pub fn apps_page(d: &Value, apps: &[App], b: &Value) -> Value {
    let ports = &d["debug_ports"];
    let gw = &d["debug_gateway"];
    let mut rows = vec![];
    if let Some(p) = gw["port"].as_u64() {
        rows.push(row(
            &s(&gw["pkg"]),
            vec![format!(":{}", p), s(&gw["bind"])],
            vec![format!("gateway {}", s(&gw["route"])), format!("roster {}", s(&gw["apps"]))],
            vec![(format!("http://{}:{}{}", s(&gw["bind"]), p, s(&gw["apps"])), format!("http://{}:{}{}", s(&gw["bind"]), p, s(&gw["apps"])))],
        ));
    }
    let routes: Vec<String> = b["api"]["debug_routes"].as_array().map(|a| a.iter().map(|r| format!("{}  {}", s(&r["path"]), s(&r["what"]))).collect()).unwrap_or_default();
    for a in apps {
        if let Some(p) = ports[&a.package].as_u64() {
            rows.push(row(&a.name, vec![format!(":{}", p), "127.0.0.1".into()], routes.clone(), vec![("ping".into(), format!("http://127.0.0.1:{}/api/system/ping", p))]));
        }
    }
    page("Apps Endpoints", "Each app's in-app debug API: loopback only, one fixed port per app (the debug-port table behind every debug-api.json), fleet bearer on everything but ping.", vec![group(&format!("{} debug APIs", rows.len()), rows)])
}

pub fn ipc_page(apps: &[App], b: &Value) -> Value {
    let tpl = b["api"]["ipc"].as_array().cloned().unwrap_or_default();
    let engine = s(&b["api"]["engine_action"]);
    let groups: Vec<Value> = apps
        .iter()
        .map(|a| {
            let mut rows: Vec<Value> = tpl
                .iter()
                .map(|t| row(&fill(&s(&t["authority"]), &a.package), vec![s(&t["kind"]), s(&t["id"])], vec![format!("{}  ·  {}", s(&t["methods"]), s(&t["guard"])), s(&t["what"])], vec![]))
                .collect();
            if !a.engines.is_empty() {
                rows.push(row(&fill(&engine, &a.package), vec!["service".into(), "engine".into()], vec![format!("binds {}", a.engines.join(", "))], vec![]));
            }
            group(&format!("{} · {}", a.name, a.package), rows)
        })
        .collect();
    page("Apps IPC", "Each app's IPC endpoints, derived from the fleet manifest and the templates in build.json::api.ipc.", groups)
}

/// #1495/#1580 the UNIFIED IPC holder as page groups: the ACL scopes, the mesh peers (the centralized access, held once
/// here instead of per app) and, per app class, every declared `/ipc/<app>/<route>` with its tool, IPC authority template,
/// method(s), required scope, status and the per-app endpoint it retires. Appended to the API > MCP and Mesh pages so the
/// registry is surfaced as API page content next to the catalogue it joins (topology view).
pub fn gateway_groups(reg: &crate::ipc::Registry, apps: &[App]) -> Vec<Value> {
    use std::collections::BTreeMap;
    let mut groups = vec![];
    let scope_rows: Vec<Value> = reg.scopes.iter().map(|(k, v)| row(k, vec![], vec![v.clone()], vec![])).collect();
    groups.push(group(&format!("Unified IPC holder /{} · {} scopes", reg.prefix.trim_start_matches('/'), reg.scopes.len()), scope_rows));
    let peer_rows: Vec<Value> = reg.peers.iter().map(|(k, sc)| row(k, sc.clone(), vec![if sc.iter().any(|s| s == "*") { "full access".to_string() } else { format!("{} scope(s)", sc.len()) }], vec![])).collect();
    groups.push(group(&format!("Mesh peers · centralized access · {}", reg.peers.len()), peer_rows));
    let mut by_class: BTreeMap<String, Vec<&crate::ipc::Entry>> = BTreeMap::new();
    for e in &reg.entries {
        by_class.entry(e.app_class.clone()).or_default().push(e);
    }
    for (class, entries) in by_class {
        let rows: Vec<Value> = entries
            .iter()
            .map(|e| {
                let mut lines = vec![format!("{}/<app>/{}  ·  {}", reg.prefix, e.route, if e.ipc.post { "POST" } else { "GET" }), format!("authority {}", e.ipc.authority)];
                if !e.ipc.methods.is_empty() {
                    lines.push(format!("methods {}", e.ipc.methods.join(" | ")));
                } else if let Some(m) = &e.ipc.method {
                    lines.push(format!("method {}", m));
                }
                if let Some(t) = &e.mcp_tool {
                    lines.push(format!("MCP tool {}", t));
                }
                if let Some(l) = &e.legacy_route {
                    lines.push(format!("retires per-app endpoint {}", l));
                }
                lines.push(e.what.clone());
                row(&e.route, vec![e.acl.clone(), e.status.clone(), e.ipc.kind.clone()], lines, vec![])
            })
            .collect();
        let cover = if class == "fleet" { format!("every manifest app ({})", apps.len()) } else { class.trim_start_matches("package:").to_string() };
        groups.push(group(&format!("{} · {}", class, cover), rows));
    }
    groups
}

