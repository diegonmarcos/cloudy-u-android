package com.diegonmarcos.cloudbrowser.sites

import org.json.JSONArray
import org.json.JSONObject
import java.net.InetSocketAddress
import java.net.Socket

/** One site Cloudy lists. [port] is set for a page the phone serves (the live probe asks it). */
data class CloudyEntry(val title: String, val url: String, val detail: String = "", val port: Int? = null)

/** #1842 one c3-infra container: its category, and its private (mesh) and public address, either of which may be absent. Each container is ONE of these. */
data class C3Container(val name: String, val category: String, val auth: String, val privateUrl: String?, val publicUrl: String?)

/** #1842 a c3-infra category and its containers, in the icon grid. */
data class C3Group(val category: String, val containers: List<C3Container>)

/** The Cloud-Webserver's launcher activity: [pkg] and the fully qualified [cls] an explicit intent names. */
data class WebserverTarget(val pkg: String, val cls: String)

/**
 * #1493 Cloudy, pure (JVM-tested in CloudyTest). Public GH-Pages: the declared repos' pages (ui.cloudy.gh_pages, derived from
 * ac_cloud-c3/data/repos_declared.json at build time) plus the live front-html pages.json ([merge]). Private Webserver: what the
 * Cloud-Webserver declares it serves (its serving endpoints and Pages sub-pages, from its build.json) plus the entries of its
 * Repos store when that file can be read ([storeEntries]); a missing store or a stopped server only shortens the list.
 * #1531 Private / Public URLs: the fleet's routes (ac_cloud-c3 data/routes.json, the Caddy routes), the mesh address of each
 * ([fleetUrls] private) or its public address (public).
 */
object Cloudy {
    fun seedPages(decl: JSONObject): List<CloudyEntry> {
        val a = decl.optJSONArray("gh_pages") ?: JSONArray()
        return (0 until a.length()).mapNotNull { i -> a.optJSONObject(i)?.let { o -> o.optString("url").takeIf { it.isNotBlank() }?.let { CloudyEntry(o.optString("name"), it) } } }
    }

    /** front-html pages.json ({pages:[{repo,url,public}]}): only the public ones, merged into [seed] by address, sorted by title. */
    fun merge(seed: List<CloudyEntry>, pagesJson: String?): List<CloudyEntry> {
        val pages = runCatching { JSONObject(pagesJson ?: "{}").optJSONArray("pages") }.getOrNull() ?: JSONArray()
        val live = (0 until pages.length()).mapNotNull { i ->
            val o = pages.optJSONObject(i) ?: return@mapNotNull null
            if (!o.optBoolean("public", true)) return@mapNotNull null
            o.optString("url").takeIf { it.isNotBlank() }?.let { CloudyEntry(o.optString("repo").ifBlank { it }, it) }
        }
        return (seed + live).distinctBy { it.url.trimEnd('/') }.sortedBy { it.title.lowercase() }
    }

    /**
     * #1856 the FULL set of pages of the repo diegonmarcos.github.io, derived from the repo itself: its front-topology.json (`{projects:[{name,category,deploy_name}]}`,
     * generated by that repo's own build) gives each project's deploy name, which is its path under [base]. Grouped by the repo's category (categories and
     * projects sorted by name, a project listed once per category); a project with no deploy name is not published and is skipped. [decl] = ui.cloudy.gh_site.
     */
    fun sitePages(topologyJson: String?, base: String): List<Pair<String, List<CloudyEntry>>> {
        val a = runCatching { JSONObject(topologyJson ?: return emptyList()).optJSONArray("projects") }.getOrNull() ?: return emptyList()
        val by = LinkedHashMap<String, MutableList<CloudyEntry>>()
        for (i in 0 until a.length()) {
            val o = a.optJSONObject(i) ?: continue
            val dn = o.optString("deploy_name").trim('/').takeIf { it.isNotBlank() } ?: continue
            val cat = o.optString("category").ifBlank { "other" }
            val list = by.getOrPut(cat) { ArrayList() }
            val url = base.trimEnd('/') + "/" + dn + "/"
            if (list.none { it.url == url }) list += CloudyEntry(o.optString("name").ifBlank { dn }, url, o.optString("framework"))
        }
        return by.map { (c, l) -> c to l.sortedBy { it.title.lowercase() } }.sortedBy { it.first.lowercase() }
    }

    /** The declared Webserver pages: [decl] = ui.cloudy.webserver (endpoints, pages, base_role). */
    fun declaredWebserver(decl: JSONObject): List<CloudyEntry> = webserverExplorers(decl) + webserverPages(decl)

    /** #1856 Local > File Explorers: the Webserver's serving endpoints (Termux, Nix, phone storage, X-Ray Device: each a file explorer over its own root). */
    fun webserverExplorers(decl: JSONObject): List<CloudyEntry> {
        val eps = decl.optJSONArray("endpoints") ?: JSONArray()
        return (0 until eps.length()).mapNotNull { eps.optJSONObject(it) }
            .map { e -> CloudyEntry(e.optString("title"), "http://${e.optString("name")}/", e.optString("summary"), e.optInt("port").takeIf { it > 0 }) }
    }

    /** #1856 Local > Pages: the Webserver's own Pages sub-pages (served on its base endpoint). */
    fun webserverPages(decl: JSONObject): List<CloudyEntry> {
        val eps = decl.optJSONArray("endpoints") ?: JSONArray()
        val list = (0 until eps.length()).mapNotNull { eps.optJSONObject(it) }
        val out = ArrayList<CloudyEntry>()
        val base = list.firstOrNull { it.optString("role") == decl.optString("base_role") }
        val pages = decl.optJSONArray("pages") ?: JSONArray()
        if (base != null) for (i in 0 until pages.length()) {
            val p = pages.optJSONObject(i) ?: continue
            out += CloudyEntry(p.optString("label"), "http://${base.optString("name")}${p.optString("route")}", p.optString("tab"), base.optInt("port").takeIf { it > 0 })
        }
        return out
    }

    /** The Repos store (`{entries:[{label,repo,exposure,port}]}`): each running site, on its own loopback port. */
    fun storeEntries(json: String?): List<CloudyEntry> {
        val a = runCatching { JSONObject(json ?: return emptyList()).optJSONArray("entries") }.getOrNull() ?: return emptyList()
        return (0 until a.length()).mapNotNull { i ->
            val o = a.optJSONObject(i) ?: return@mapNotNull null
            val port = o.optInt("port").takeIf { it in 1..65535 } ?: return@mapNotNull null
            CloudyEntry(o.optString("label").ifBlank { o.optString("repo") }, "http://127.0.0.1:$port/",
                listOf(o.optString("repo"), o.optString("exposure")).filter { it.isNotBlank() }.joinToString(" · "), port)
        }
    }

    /** Does something answer on loopback [port]? BLOCKING: off the main thread. */
    fun probe(port: Int, timeoutMs: Int): Boolean =
        runCatching { Socket().use { it.connect(InetSocketAddress("127.0.0.1", port), timeoutMs); true } }.getOrDefault(false)

    /** The fleet's URLs from the declared routes: each route's mesh address (private, plain http on the mesh) or public address (https), by name. */
    fun fleetUrls(routes: JSONArray?, private_: Boolean, privateScheme: String, publicScheme: String): List<CloudyEntry> =
        (0 until (routes?.length() ?: 0)).mapNotNull { i ->
            val o = routes?.optJSONObject(i) ?: return@mapNotNull null
            val addr = o.optString(if (private_) "private_url" else "public_url").takeIf { it.isNotBlank() } ?: return@mapNotNull null
            CloudyEntry(o.optString("container"), (if (private_) privateScheme else publicScheme) + addr,
                listOf(o.optString("category"), o.optString("auth_type")).filter { it.isNotBlank() }.joinToString(" · "))
        }.distinctBy { it.title + it.url }.sortedBy { it.title.lowercase() }

    /**
     * #1842 Cloudy C3 Urls: the private and public pages merged. The fleet's routes (ac_cloud-c3 data/routes.json) grouped by their c3-infra category,
     * each container ONCE with both addresses (the very ones [fleetUrls] lists for the private and the public page), categories and containers sorted by name.
     */
    fun c3Groups(routes: JSONArray?, privateScheme: String, publicScheme: String): List<C3Group> {
        val byName = LinkedHashMap<String, C3Container>()
        for (i in 0 until (routes?.length() ?: 0)) {
            val o = routes?.optJSONObject(i) ?: continue
            val name = o.optString("container").takeIf { it.isNotBlank() } ?: continue
            val priv = o.optString("private_url").takeIf { it.isNotBlank() }?.let { privateScheme + it }
            val pub = o.optString("public_url").takeIf { it.isNotBlank() }?.let { publicScheme + it }
            val old = byName[name]
            byName[name] = if (old == null) C3Container(name, o.optString("category"), o.optString("auth_type"), priv, pub)
            else old.copy(privateUrl = old.privateUrl ?: priv, publicUrl = old.publicUrl ?: pub, category = old.category.ifBlank { o.optString("category") })
        }
        return byName.values.groupBy { it.category.ifBlank { "other" } }
            .map { (cat, cs) -> C3Group(cat, cs.sortedBy { it.name.lowercase() }) }.sortedBy { it.category.lowercase() }
    }

    /** The explicit-intent target of the Cloud-Webserver: [decl] = ui.cloudy.webserver (package, launcher_activity); null when either is not declared. */
    fun webserverTarget(decl: JSONObject): WebserverTarget? {
        val pkg = decl.optString("package").takeIf { it.isNotBlank() } ?: return null
        val act = decl.optString("launcher_activity").takeIf { it.isNotBlank() } ?: return null
        return WebserverTarget(pkg, if (act.startsWith(".")) pkg + act else if ('.' in act) act else "$pkg.$act")
    }
}
